test('Card 阅读应用：interactive 与 disabled 边界、长按恢复和移动取消', async ({ page }) => {
  await page.goto('/?understanding=card')
  const click = page.locator('.reading-click')
  await expect(click).toHaveClass(/bing-card--back-axis-y/)
  await page.getByRole('button', { name: '卡片内说明按钮', exact: true }).click()
  await expect(click).not.toHaveClass(/is-flipped/)
  await page.getByRole('button', { name: '卡片内说明按钮', exact: true }).click()
  await click.locator('.bing-card__body p').click()
  await expect(click).toHaveClass(/is-flipped/)
  await expect(click).not.toHaveAttribute('tabindex')
  const childButton = page.getByRole('button', { name: '插槽按钮', exact: true })
  await expect(childButton).toBeEnabled()
  await childButton.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('status')).toHaveText('长按：0；业务点击：1')
  await expect(page.locator('.reading-disabled')).not.toHaveClass(/is-flipped/)
  const press = page.locator('.reading-press')
  await press.scrollIntoViewIfNeeded()
  const box = (await press.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await expect(press).toHaveClass(/is-flipped/)
  await page.mouse.up()
  await expect(press).not.toHaveClass(/is-flipped/)
  await expect(page.getByRole('status')).toHaveText('长按：1；业务点击：1')
  await page.mouse.move(box.x + 30, box.y + 30)
  await page.mouse.down()
  await page.mouse.move(box.x + 60, box.y + 30)
  await expect(press).not.toHaveClass(/is-pressing/)
  await page.mouse.up()
  await expect(page.getByRole('status')).toHaveText('长按：1；业务点击：1')
  await page.getByRole('button', { name: '查看关键说明', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByText('无需翻面也能阅读的详细说明。', { exact: true })).toBeVisible()
})

test('Card 导出：单层磨砂、主题默认值与减少动态效果', async ({ page }, info) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/?component=card&example=basic')
  const card = page.locator('.bing-card')
  await expect(card).toHaveClass(/has-entered/)
  await expect(card).toHaveCSS('--bing-card-glass-opacity', /^0?\.86$/)
  await expect(card).toHaveCSS('--bing-card-glass-saturation', '1.05')
  await expect(card.locator('.bing-card__surface')).toHaveCSS('backdrop-filter', 'none')
  await expect(card.locator('.bing-card__front')).toHaveCSS('backdrop-filter', 'blur(16px) saturate(1.05)')
  await page.evaluate(() => { document.documentElement.dataset.bingTheme = 'dark' })
  await expect(card).toHaveCSS('--bing-card-glass-opacity', /^0?\.92$/)
  await card.hover()
  expect(await card.locator('.bing-card__surface').evaluate(node => new DOMMatrix(getComputedStyle(node).transform).isIdentity)).toBe(true)
  await card.screenshot({ path: info.outputPath('card-dark-reduced-motion.png'), animations: 'disabled' })
})
