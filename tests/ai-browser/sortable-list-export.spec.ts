test('SortableList 阅读应用：归一化不回写外部值', async ({ page }) => {
  await page.goto('/?understanding=sortable-list')
  await expect.poll(() => sortableKeys(page.getByRole('list'))).toEqual(['b','a','c'])
  await expect(page.locator('#model')).toHaveText('["b","missing","b"]')
  await expect(page.locator('#events')).toHaveText('[]')
  await page.getByRole('button', { name: '移动 乙' }).press('End')
  await expect(page.locator('#model')).toHaveText('["a","c","b"]')
  await expect(page.locator('#detail')).toContainText('"from":0,"to":2')
  await expect(page.locator('#events')).toHaveText('["update","reorder"]')
})
for (const live of [false, true]) test(`SortableList 阅读应用：指针 ${live ? 'live' : 'drop'} 提交时机`, async ({ page }) => {
  await page.goto('/?understanding=sortable-list')
  await page.getByRole('button', { name: '重置有效顺序' }).click()
  if (live) await page.getByRole('checkbox', { name: '实时提交' }).check()
  const list = page.getByRole('list', { name: '阅读排序' })
  await startSortableDrag(page, list, 'a', 'c')
  // 拖动时会有临时镜像节点；投影顺序以 drag 载荷为准，释放后再检查真实行。
  await expect(page.locator('#detail')).toContainText('"order":["b","c","a"]')
  await expect(page.locator('#model')).toHaveText(live ? '["b","c","a"]' : '["a","b","c"]')
  if (!live) await expect(page.locator('#events')).not.toContainText('reorder')
  await page.mouse.up()
  await expect(page.locator('#model')).toHaveText('["b","c","a"]')
  await expect.poll(() => sortableKeys(list)).toEqual(['b','c','a'])
  await expect(page.locator('#events')).toContainText('"end"]')
  await expect(page.locator('#events')).toContainText('"update","reorder"')
})
for (const live of [false, true]) test(`SortableList 阅读应用：取消 ${live ? 'live' : 'drop'} 拖拽`, async ({ page }) => {
  await page.goto('/?understanding=sortable-list'); await page.getByRole('button', { name: '重置有效顺序' }).click()
  if (live) await page.getByRole('checkbox', { name: '实时提交' }).check()
  const list = page.getByRole('list', { name: '阅读排序' })
  await startSortableDrag(page, list, 'a', 'c')
  await expect(page.locator('#detail')).toContainText('"order":["b","c","a"]')
  await page.keyboard.press('Escape'); await page.mouse.up()
  await expect(list).not.toHaveClass(/is-dragging/)
  await expect(page.locator('#events')).not.toContainText('"end"')
  await expect(page.locator('#model')).toHaveText(live ? '["b","c","a"]' : '["a","b","c"]')
})
test('SortableList 阅读应用：禁用与受控更新被忽略', async ({ page }) => {
  await page.goto('/?understanding=sortable-list'); await page.getByRole('button', { name: '重置有效顺序' }).click()
  await page.getByRole('checkbox', { name: '忽略更新' }).check()
  await page.getByRole('button', { name: '移动 甲' }).press('ArrowDown')
  await expect.poll(() => sortableKeys(page.getByRole('list'))).toEqual(['a','b','c'])
  await expect(page.locator('#events')).toHaveText('["update","reorder"]')
  await page.getByRole('checkbox', { name: '禁用列表' }).check()
  await page.getByRole('button', { name: '移动 甲' }).press('End')
  await expect(page.locator('#events')).toHaveText('["update","reorder"]')
})
