import { expect, test } from '@playwright/test'

test('Autocomplete 导出：行尾按钮、禁用项与键盘选择互不串联', async ({ page }) => {
  await page.goto('/?component=autocomplete&example=actions')
  const input = page.getByRole('combobox')
  await input.click()
  await input.press('F2')
  await expect(page.getByRole('button', { name: /在新标签页打开：REQ-7/ })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('status')).toContainText('新标签页：REQ-7')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Space')
  await expect(page.getByRole('status')).toContainText('新标签页：REQ-4')
  await expect(page.getByRole('button', { name: /在新标签页打开：REQ-9/ })).toBeDisabled()
  await page.keyboard.press('ArrowLeft')
  await input.press('Enter')
  await expect(page.getByRole('status')).toContainText('当前页：REQ-4')
  await expect(input).toHaveValue('REQ')
})

test('Autocomplete 导出：空输入开关覆盖聚焦、方向键、空白及清除', async ({ page }) => {
  await page.goto('/?component=autocomplete&example=controlled')
  await page.getByRole('button', { name: '聚焦搜索', exact: true }).click()
  const input = page.getByRole('combobox')
  await expect(input).toBeFocused()
  await expect(input).toHaveAttribute('aria-expanded', 'false')
  await input.press('ArrowDown')
  await expect(input).toHaveAttribute('aria-expanded', 'false')
  await input.fill('   ')
  await expect(input).toHaveAttribute('aria-expanded', 'false')
  await input.fill('req7')
  await expect(page.getByRole('option')).toHaveCount(1)
  await page.getByRole('button', { name: '清空输入', exact: true }).click()
  await expect(input).toHaveValue('')
  await expect(input).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('listbox')).toHaveCount(0)
})

test('Autocomplete 导出示例：筛选选择、受控输入及失败重试', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/?component=autocomplete&example=basic')
  await page.getByRole('combobox').fill('布局')
  await page.getByRole('combobox').press('Enter')
  await expect(page.getByRole('status')).toContainText('REQ-4（编辑器布局优化）')
  await page.goto('/?component=autocomplete&example=controlled')
  await page.getByRole('combobox').fill('req7')
  await page.getByRole('combobox').press('Enter')
  await expect(page.getByRole('status')).toContainText('REQ-7（付款分类）；关键字保留为：req7')
  await page.getByRole('button', { name: '模拟加载失败' }).click()
  await expect(page.getByRole('option')).toHaveCount(0)
  await page.getByRole('button', { name: '重试', exact: true }).click()
  await expect(page.getByRole('option')).toHaveCount(1)
  expect(errors).toEqual([])
})

test('Autocomplete 阅读应用：focus、禁用项、IME 确认与选择分开', async ({ page }) => {
  await page.goto('/?understanding=autocomplete')
  await page.getByRole('button', { name: '聚焦搜索' }).click()
  const input = page.getByRole('combobox')
  await expect(input).toBeFocused()
  await input.fill('中文')
  await input.dispatchEvent('compositionstart')
  await input.press('Enter')
  await expect(page.getByRole('status')).toHaveText('选中 无；输入 中文')
  await input.dispatchEvent('compositionend')
  await input.press('Enter')
  await expect(page.getByRole('status')).toHaveText('选中 2；输入 中文')
  await expect(page.getByRole('listbox')).toHaveCount(0)
})
