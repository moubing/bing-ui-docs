import { expect, test, type Page } from '@playwright/test'

const errors = new WeakMap<Page, string[]>()
test.beforeEach(({ page }) => {
  const messages: string[] = []
  errors.set(page, messages)
  page.on('pageerror', error => messages.push(error.message))
  page.on('console', message => {
    if (/failed to resolve component|unhandled error/i.test(message.text())) messages.push(message.text())
  })
})
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))

test('RadioGroup 导出基础与 options：单值、null 清空、禁用与重复点击', async ({ page }) => {
  await page.goto('/?component=radio-group&example=basic')
  const standard = page.getByRole('radio', { name: /^标准模式/ })
  await expect(standard).toBeChecked()
  await standard.locator('..').click()
  await expect(standard).toBeChecked()
  await page.getByRole('button', { name: '清空外部值', exact: true }).click()
  await expect(page.locator('input:checked')).toHaveCount(0)
  await expect(page.getByRole('status')).toContainText('未选择')
  await page.getByRole('button', { name: '选择推荐', exact: true }).click()
  await expect(standard).toBeChecked()
  await expect(page.getByRole('radio', { name: /^实验模式/ })).toBeDisabled()
  await page.goto('/?component=radio-group&example=options')
  await page.getByRole('radio', { name: '深色', exact: true }).locator('..').click()
  await expect(page.getByText('当前主题：dark', { exact: true })).toBeVisible()
  await expect(page.locator('input:checked')).toHaveCount(1)
})

test('RadioGroup 导出插槽：替代 options，子项共用模型与名称', async ({ page }) => {
  await page.goto('/?component=radio-group&example=slot')
  await expect(page.getByRole('radio')).toHaveCount(3)
  await expect(page.getByText('这项不会显示', { exact: true })).toHaveCount(0)
  await page.getByRole('radio', { name: /^使用说明/ }).locator('..').click()
  await expect(page.getByRole('status')).toHaveText('当前值：usage')
  await expect(page.locator('input:checked')).toHaveCount(1)
  for (const radio of await page.getByRole('radio').all()) await expect(radio).toHaveAttribute('name', 'doc-scope')
})

test('RadioGroup 导出键盘：跳过禁用、循环、完整 change 参数及组级焦点边界', async ({ page }) => {
  await page.goto('/?component=radio-group&example=keyboard')
  const first = page.getByRole('radio', { name: /^第一步/ })
  const last = page.getByRole('radio', { name: /^第三步/ })
  await first.focus()
  await first.press('ArrowRight')
  await expect(last).toBeFocused()
  await expect(last).toBeChecked()
  await expect(page.getByRole('status')).toContainText('step-3；原始事件：change')
  await expect(page.getByText('进入组：1；离开组：0', { exact: true })).toBeVisible()
  await last.press('ArrowDown')
  await expect(first).toBeChecked()
  await page.getByRole('button', { name: '组外按钮', exact: true }).focus()
  await expect(page.getByText('进入组：1；离开组：1', { exact: true })).toBeVisible()
})

test('RadioGroup 阅读应用：false 与 0 保留类型，不同组不会互相取消选择', async ({ page }) => {
  await page.goto('/?understanding=radio-group')
  const ids = await page.locator('[role="radiogroup"], input[type="radio"]').evaluateAll(nodes => nodes.map(node => node.id))
  expect(ids.every(Boolean)).toBe(true)
  expect(new Set(ids).size).toBe(ids.length)
  const names = await page.getByRole('radiogroup').evaluateAll(nodes => nodes.map(node => node.querySelector('input')?.name))
  expect(names.every(Boolean)).toBe(true)
  expect(new Set(names).size).toBe(2)
  await page.getByRole('radio', { name: '暂不启用', exact: true }).locator('..').click()
  await expect(page.getByRole('status')).toHaveText('决策：false；重试：0；类型：number')
  await expect(page.getByText('boolean:false:change', { exact: true })).toBeVisible()
  await expect(page.getByRole('radio', { name: '不重试', exact: true })).toBeChecked()
  await page.getByRole('radio', { name: '两次', exact: true }).locator('..').click()
  await expect(page.getByRole('radio', { name: '暂不启用', exact: true })).toBeChecked()
  await page.getByRole('button', { name: '清空决策', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('决策：未选择；重试：2；类型：number')
})
