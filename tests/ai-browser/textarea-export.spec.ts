import { expect, test, type Page } from '@playwright/test'

const errors = new WeakMap<Page, string[]>()
test.beforeEach(({ page }) => {
  const messages: string[] = []
  errors.set(page, messages)
  page.on('pageerror', error => messages.push(error.message))
})
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))

test('Textarea 导出基础和自动高度：文本同步、增高及最大行数', async ({ page }) => {
  await page.goto('/?component=textarea&example=basic')
  await page.getByRole('textbox', { name: '基础 Textarea 示例', exact: true }).fill('新的备注')
  await expect(page.getByRole('status')).toHaveText('字符数：4')
  await expect(page.getByRole('textbox', { name: '基础 Textarea 示例', exact: true })).toHaveAttribute('data-smooth-caret', '')
  await page.goto('/?component=textarea&example=autosize')
  const auto = page.getByRole('textbox', { name: '自动增高', exact: true })
  const height = await auto.evaluate(node => node.getBoundingClientRect().height)
  await auto.fill(Array.from({ length: 12 }, (_, i) => `行${i}`).join('\n'))
  await expect.poll(() => auto.evaluate(node => node.getBoundingClientRect().height)).toBeGreaterThan(height)
  const limited = page.getByRole('textbox', { name: '限制高度与长度', exact: true })
  await limited.fill(Array.from({ length: 15 }, () => '行').join('\n'))
  await limited.press('ControlOrMeta+End')
  await expect(limited).toHaveAttribute('data-smooth-caret', '')
  await expect(limited).toHaveCSS('overflow-y', 'auto')
  const metrics = await limited.evaluate(node => ({ height: node.getBoundingClientRect().height, line: parseFloat(getComputedStyle(node).lineHeight), padding: parseFloat(getComputedStyle(node).paddingTop) + parseFloat(getComputedStyle(node).paddingBottom) }))
  expect(metrics.height).toBeLessThanOrEqual(metrics.line * 6 + metrics.padding + 2)
})

test('Textarea 导出状态与事件：独立模型、完整 input 参数、keydown、清除和焦点', async ({ page }) => {
  await page.goto('/?component=textarea&example=resize')
  const noResize = page.getByRole('textbox', { name: '禁止拖拽', exact: true })
  await expect(noResize).toHaveCSS('resize', 'none')
  await noResize.fill('独立编辑')
  await expect(page.getByRole('textbox', { name: '垂直调整', exact: true })).toHaveValue('只允许垂直调整')
  await expect(page.getByRole('textbox', { name: '错误状态', exact: true })).toHaveAttribute('aria-invalid', 'true')
  await page.goto('/?component=textarea&example=events')
  const event = page.getByRole('textbox', { name: '事件示例', exact: true })
  await event.fill('abc')
  await expect(page.getByRole('status')).toHaveText('input：3 个字符；原始事件：input')
  await event.press('ArrowLeft')
  await expect(page.getByText('最近按键：ArrowLeft', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '清空文本', exact: true }).click()
  await expect(event).toHaveValue('')
  await expect(event).toBeFocused()
  await expect(page.getByRole('status')).toHaveText('clear：已清空')
  await page.getByRole('button', { name: '移出焦点', exact: true }).focus()
  await expect(page.getByRole('status')).toHaveText('blur：失去焦点')
})

test('Textarea 导出方法：ref、原生元素、focus/blur 和选区', async ({ page }) => {
  await page.goto('/?component=textarea&example=methods')
  const textarea = page.getByRole('textbox', { name: '实例方法示例', exact: true })
  await page.getByRole('button', { name: 'focus', exact: true }).click()
  await expect(textarea).toBeFocused()
  await page.getByRole('button', { name: 'select', exact: true }).click()
  expect(await textarea.evaluate((node: HTMLTextAreaElement) => [node.selectionStart, node.selectionEnd])).toEqual([0, (await textarea.inputValue()).length])
  await expect(page.getByRole('status')).toHaveText('选中文本：' + await textarea.inputValue())
  await page.getByRole('button', { name: 'blur', exact: true }).click()
  await expect(textarea).not.toBeFocused()
})

test('Textarea 阅读应用：emoji 计数、清除不发 input、程序赋值不截断', async ({ page }) => {
  await page.goto('/?understanding=textarea')
  await expect(page.locator('.bing-textarea__count')).toHaveText('2/2')
  const textarea = page.getByRole('textbox', { name: '短备注', exact: true })
  await textarea.focus()
  await page.getByRole('button', { name: '清空文本', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('模型长度：0；input：0；clear：1')
  await expect(textarea).toBeFocused()
  await textarea.pressSequentially('abc')
  await expect(textarea).toHaveValue('ab')
  await page.getByRole('button', { name: '程序赋值', exact: true }).click()
  await expect(textarea).toHaveValue('超出最大长度')
  await expect(page.locator('.bing-textarea__count')).toHaveText('6/2')
})

test('Textarea 阅读应用：只读选择、清除边界和动态关闭自动高度', async ({ page }) => {
  await page.goto('/?understanding=textarea')
  const textarea = page.getByRole('textbox', { name: '短备注', exact: true })
  const original = await textarea.elementHandle()
  await page.getByRole('button', { name: '切换自动高度', exact: true }).click()
  await page.getByRole('button', { name: '填入多行', exact: true }).click()
  await expect.poll(() => textarea.evaluate(node => node.style.height)).not.toBe('')
  await page.getByRole('button', { name: '切换自动高度', exact: true }).click()
  await expect.poll(() => textarea.evaluate(node => [node.style.height, node.style.overflowY])).toEqual(['', ''])
  expect(await original!.evaluate(node => node.isConnected)).toBe(true)
  await page.getByRole('button', { name: '切换只读', exact: true }).click()
  await textarea.focus()
  await textarea.press('ControlOrMeta+A')
  await expect(textarea).toBeFocused()
  expect(await textarea.evaluate((node: HTMLTextAreaElement) => node.selectionEnd - node.selectionStart)).toBe((await textarea.inputValue()).length)
  await expect(page.getByRole('button', { name: '清空文本', exact: true })).toHaveCount(0)
  const value = await textarea.inputValue()
  await textarea.press('x')
  await expect(textarea).toHaveValue(value)
})
