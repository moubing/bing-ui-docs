import { expect, test, type Page } from '@playwright/test'
const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => { const messages: string[] = []; errors.set(page, messages); page.on('pageerror', error => messages.push(error.message)); await page.emulateMedia({ reducedMotion: 'reduce' }) })
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))
const active = (page: Page) => page.locator('.bing-deck-transition__card.is-active')

test('DeckTransition 导出基础：按钮键盘操作和真实洗牌动画', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/?component=deck-transition&example=basic')
  await expect(active(page)).toContainText('确认组件边界')
  await page.getByRole('button', { name: '切换下一张', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('status')).toHaveText('当前值：build')
  await expect(active(page).locator('.story')).toHaveClass(/is-animating/)
  await expect(active(page).locator('.story')).not.toHaveClass(/is-animating/)
  await expect(active(page)).toHaveCSS('opacity', '1')
})

test('DeckTransition 导出配置：外部直接定位，内部选择发事件', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/?component=deck-transition&example=playground')
  await page.getByRole('button', { name: '选择规划', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('当前值：plan；change：等待切换')
  await expect(active(page).locator('.story')).not.toHaveClass(/is-animating/)
  await expect(active(page)).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
  await page.getByRole('button', { name: '下一张', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('规划 -> 编写')
})

test('DeckTransition 导出 controls：非循环终点和业务重置', async ({ page }) => {
  await page.goto('/?component=deck-transition&example=controls')
  const next = page.getByRole('button', { name: '下一张', exact: true })
  await next.click(); await expect(page.getByRole('status')).toHaveText('当前值：build')
  await next.click(); await expect(next).toBeDisabled()
  await expect(page.getByRole('status')).toHaveText('当前值：ship')
  await page.getByRole('button', { name: '返回第一张', exact: true }).click()
  await expect(next).toBeEnabled()
  await expect(active(page)).toContainText('确认组件边界')
})

test('DeckTransition 阅读应用：next 不跳过禁用项，外部赋值不受 disabled 限制', async ({ page }) => {
  await page.goto('/?understanding=deck-transition')
  await page.getByRole('button', { name: '阅读下一张', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('模型 a；更新 0；变化 0')
  await page.locator('#disabled').check()
  await expect(page.getByRole('button', { name: '阅读下一张', exact: true })).toBeDisabled()
  await page.locator('#external').click()
  await expect(page.getByRole('status')).toHaveText('模型 b；更新 0；变化 0')
  await expect(active(page)).toContainText('乙')
  await expect(page.getByRole('button', { name: '甲操作', exact: true })).toHaveCount(0)
})

test('DeckTransition 阅读应用：正负滚轮均向前，单次阈值和隐藏控制', async ({ page }) => {
  await page.goto('/?understanding=deck-transition')
  await page.locator('#middle-disabled').uncheck()
  await page.locator('#controls').uncheck()
  await expect(page.getByRole('button', { name: '阅读下一张', exact: true })).toHaveCount(0)
  const root = page.locator('.bing-deck-transition')
  await root.dispatchEvent('wheel', { deltaX: 24, deltaY: 0 })
  await root.dispatchEvent('wheel', { deltaX: 24, deltaY: 0 })
  await expect(page.getByRole('status')).toHaveText('模型 a；更新 0；变化 0')
  await root.dispatchEvent('wheel', { deltaX: -30, deltaY: 0 })
  await expect(page.getByRole('status')).toHaveText('模型 b；更新 1；变化 1')
  await root.dispatchEvent('wheel', { deltaX: 30, deltaY: 0 })
  await expect(page.getByRole('status')).toHaveText('模型 c；更新 2；变化 2')
  await page.locator('#loop').uncheck()
  await root.dispatchEvent('wheel', { deltaX: -30, deltaY: 0 })
  await expect(page.getByRole('status')).toHaveText('模型 c；更新 2；变化 2')
})

test('DeckTransition 阅读应用：受控更新被忽略时，卡片位置与模型不一致', async ({ page }) => {
  await page.goto('/?understanding=deck-transition')
  await page.locator('#middle-disabled').uncheck()
  await page.locator('#sync').uncheck()
  await page.getByRole('button', { name: '阅读下一张', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('模型 a；更新 1；变化 1')
  await expect(active(page)).toContainText('甲')
  await expect(page.locator('.bing-deck-transition__card').nth(1)).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
  await expect(active(page)).not.toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
})
