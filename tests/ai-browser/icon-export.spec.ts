import { expect, test, type Page } from '@playwright/test'

const errors = new WeakMap<Page, string[]>()
test.beforeEach(({ page }) => { const messages: string[] = []; errors.set(page, messages); page.on('pageerror', error => messages.push(error.message)) })
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))

test('Icon 导出：实际尺寸、语义色和装饰属性', async ({ page }) => {
  await page.goto('/?component=icon&example=basic')
  await expect(page.locator('.bing-icon')).toHaveCSS('width', '24px')
  await expect(page.locator('.bing-icon')).toHaveCSS('stroke-width', '1.75px')
  await expect(page.locator('.bing-icon')).toHaveAttribute('aria-hidden', 'true')
  await expect(page.locator('.bing-icon')).not.toHaveAttribute('aria-label')
  await page.goto('/?component=icon&example=sizes')
  const icons = page.locator('.bing-icon')
  await expect(icons).toHaveCount(7)
  await expect(icons.first()).toHaveCSS('stroke-width', '1.75px')
  for (const [index, width] of [14, 16, 20, 24, 32, 28, 36].entries()) await expect(icons.nth(index)).toHaveCSS('width', width + 'px')
  await page.goto('/?component=icon&example=tones')
  await expect(page.locator('.bing-icon')).toHaveCount(7)
  await expect(page.locator('.bing-icon--inherit')).toHaveCSS('color', 'rgb(102, 51, 153)')
  expect(await page.locator('.bing-icon--danger').evaluate(node => getComputedStyle(node).color)).not.toBe(await page.locator('.bing-icon--success').evaluate(node => getComputedStyle(node).color))
  await page.goto('/?component=icon&example=accessibility')
  await expect(page.getByRole('img', { name: '打开通知', exact: true })).toBeVisible()
  await expect(page.getByRole('img')).toHaveCount(1)
})

test('Icon 阅读应用：本地图标属性透传和装饰优先级', async ({ page }) => {
  await page.goto('/?understanding=icon')
  const icon = page.locator('svg')
  await expect(page.getByRole('img', { name: '添加条目', exact: true })).toBeVisible()
  await expect(icon).toHaveCSS('width', '28px')
  await expect(icon).toHaveCSS('stroke-width', '2.5px')
  await page.getByRole('checkbox', { name: '装饰', exact: true }).check()
  await expect(icon).toHaveAttribute('aria-hidden', 'true')
  await expect(icon).not.toHaveAttribute('aria-label')
  await page.getByRole('checkbox', { name: '装饰', exact: true }).uncheck()
  await page.getByRole('textbox', { name: '名称', exact: true }).fill('')
  await expect(icon).toHaveAttribute('aria-hidden', 'true')
  await expect(icon).not.toHaveAttribute('role')
  await page.getByRole('textbox', { name: '名称', exact: true }).fill('恢复名称')
  await expect(page.getByRole('img', { name: '恢复名称', exact: true })).toBeVisible()
})
