test('TreeSelect 多实例及 Dialog：内部 ID 隔离，Escape 关闭当前层并恢复焦点', async ({ page }) => {
  await page.goto('/?understanding=tree-select&composition=1')
  await page.getByRole('button', { name: '打开树选择表单', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '树选择组合', exact: true })
  const first = page.getByRole('combobox', { name: '第一组树', exact: true })
  const second = page.getByRole('combobox', { name: '第二组树', exact: true })
  // 可选父节点的后代全部禁用时，默认级联归一化仍不会保留父 Tag。
  await expect(dialog.locator('.bing-tree-select__tags-value .bing-tree-select__value-tag')).toHaveCount(0)
  await first.click()
  const firstTreeId = await page.getByRole('tree').getAttribute('id')
  const firstNodeIds = await page.getByRole('treeitem').evaluateAll(nodes => nodes.map(node => node.id))
  await panel(page).getByRole('combobox').press('Escape')
  await expect(first).toBeFocused()
  await expect(dialog).toBeVisible()
  await second.click()
  expect(await page.getByRole('tree').getAttribute('id')).not.toBe(firstTreeId)
  const secondNodeIds = await page.getByRole('treeitem').evaluateAll(nodes => nodes.map(node => node.id))
  expect(secondNodeIds.some(id => firstNodeIds.includes(id))).toBe(false)
  await node(page, '普通节点').click()
  await expect(second).toBeFocused()
  await second.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button', { name: '打开树选择表单', exact: true })).toBeFocused()
})

