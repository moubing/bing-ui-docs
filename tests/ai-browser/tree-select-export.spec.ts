import { expect, test, type Page } from '@playwright/test'

const errors = new WeakMap<Page, string[]>()
const panel = (page: Page) => page.locator('.bing-tree-select__panel')
const node = (page: Page, label: string) => page.getByRole('treeitem').filter({ has: page.getByText(label, { exact: true }) })
const model = (page: Page) => page.locator('#model')
test.beforeEach(async ({ page }) => {
  const messages: string[] = []; errors.set(page, messages)
  page.on('pageerror', error => messages.push(error.message))
  await page.emulateMedia({ reducedMotion: 'reduce' })
})
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))

test('TreeSelect：搜索内收起、清空恢复及活动后代语义', async ({ page }) => {
  await page.goto('/?component=tree-select&example=basic')
  await page.getByRole('combobox', { name: '选择组件节点', exact: true }).click()
  const search = panel(page).getByRole('combobox')
  await search.fill('BingInput')
  await expect(node(page, 'BingInput').locator('mark')).toHaveText('BingInput')
  await expect(node(page, 'BingInput')).toHaveAttribute('aria-setsize', '1')
  await search.press('End')
  await expect(search).toHaveAttribute('aria-activedescendant', (await node(page, 'BingInput').getAttribute('id'))!)
  await node(page, '组件库').locator('.bing-tree-select__expand').click()
  await expect(page.getByRole('treeitem')).toHaveCount(1)
  await expect(search).toHaveAttribute('aria-activedescendant', (await node(page, '组件库').getAttribute('id'))!)
  await search.fill('')
  await expect(node(page, 'BingInput')).toBeVisible()
  await expect(node(page, 'BingTreeSelect')).toBeVisible()
})

