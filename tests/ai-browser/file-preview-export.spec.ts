import { checkNestedPreviews } from '../browser/file-preview-nested'
import { expect, test, type Page, type Route } from '@playwright/test'

const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => {
  const messages: string[] = []; errors.set(page, messages)
  page.on('pageerror', error => messages.push(error.message))
  await page.emulateMedia({ reducedMotion: 'reduce' })
})
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))
const businessClick = (page: Page, id: string) => page.locator('#' + id).evaluate((node: HTMLElement) => node.click())
const text = (page: Page) => page.locator('.bing-file-preview__text')
const closeButton = (page: Page) => page.getByRole('button', { name: '关闭文件预览', exact: true })
async function close(page: Page) { await closeButton(page).click(); await expect(page.getByRole('dialog')).toHaveCount(0) }

test('FilePreview 导出基础：完整 JSON、高亮、下载和关闭反馈', async ({ page }) => {
  await page.goto('/?component=file-preview&example=basic')
  const entry = page.getByRole('button', { name: '打开预览', exact: true })
  await entry.click()
  await expect(page.getByRole('dialog', { name: '文件预览', exact: true })).toBeFocused()
  await expect(text(page)).toContainText('"component": "BingFilePreview"')
  await expect(page.locator('.bing-file-preview__json-token').first()).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载文件', exact: true }).click()
  const file = await download; expect(file.suggestedFilename()).toBe('component.config.json'); await file.delete()
  await expect(page.getByRole('status')).toContainText('下载：component.config.json (json)')
  await close(page)
  await expect(page.getByRole('status')).toHaveText('关闭：close')
  await expect(entry).toBeFocused()
})

