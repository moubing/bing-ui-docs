test('FilePreview 阅读应用：忽略关闭模型、业务关闭及跨分支滚动锁', async ({ page }) => {
  await page.goto('/?understanding=file-preview')
  const before = await page.evaluate(() => document.body.style.overflow)
  await page.locator('#accept-close').uncheck()
  await page.locator('#open').click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.locator('#state')).toContainText('"events":["model:false","close:escape"]')
  await businessClick(page, 'external-close')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await page.evaluate(() => document.body.style.overflow)).toBe(before)
  await page.locator('#accept-close').check()
  await page.locator('#open').click()
  await businessClick(page, 'image')
  await expect(page.getByRole('dialog', { name: '图片预览', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '关闭预览', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  // 0.6.0 仍不在 image 分支关闭时释放原非图片分支的锁，所以正文要求先关闭再换类型。
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('hidden')
  await page.locator('#unmount').click()
  expect(await page.evaluate(() => document.body.style.overflow)).toBe(before)
})

