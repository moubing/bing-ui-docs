test('FilePreview 阅读应用：过期 fetch 不覆盖新文件，HTTP 错误单独通知', async ({ page }) => {
  let slow: Route | undefined
  await page.route('**/file-fixture/*', route => {
    if (route.request().url().endsWith('slow.txt')) { slow = route; return }
    return route.fulfill({ status: 404, body: 'missing' })
  })
  await page.goto('/?understanding=file-preview')
  await page.locator('#remote').click()
  await page.locator('#open').click()
  await expect(page.getByText('正在加载文件', { exact: true })).toBeVisible()
  await expect.poll(() => Boolean(slow)).toBe(true)
  await businessClick(page, 'empty')
  await slow!.fulfill({ status: 200, body: '过期内容' })
  await expect(text(page)).toHaveText('')
  await businessClick(page, 'missing')
  await expect(page.getByText('文件加载失败，请重试或下载后查看。', { exact: true })).toBeVisible()
  await expect(page.locator('#state')).toContainText('"events":["error:文件请求失败（404）"]')
})

test('FilePreview 阅读应用：下载与外部打开地址不同，unknown 不渲染预览', async ({ page, context }) => {
  await context.route('**/file-fixture/*', route => route.fulfill({ status: 200, contentType: 'text/html', body: '<h1>可信转换页</h1>' }))
  await page.goto('/?understanding=file-preview')
  await page.locator('#download').click()
  await page.locator('#open').click()
  await expect(page.getByRole('button', { name: '在新标签页打开文件', exact: true })).toHaveCount(0)
  await businessClick(page, 'converted')
  await expect(page.frameLocator('iframe').getByRole('heading', { name: '可信转换页', exact: true })).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载文件', exact: true }).click()
  const file = await download; expect(file.url()).toContain('/file-fixture/download.docx'); await file.delete()
  const popupPromise = page.waitForEvent('popup')
  await page.getByRole('button', { name: '在新标签页打开文件', exact: true }).click()
  const popup = await popupPromise; await expect(popup).toHaveURL(/\/file-fixture\/converted.html$/); await popup.close()
  await expect(page.locator('#state')).toContainText('download:docx:book.docx')
  await expect(page.locator('#state')).toContainText('external:docx:book.docx')
  await businessClick(page, 'unknown')
  await expect(page.getByRole('heading', { name: '暂不支持此文件预览', exact: true })).toBeVisible()
  await expect(page.locator('iframe')).toHaveCount(0)
})

