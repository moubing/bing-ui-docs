  await businessClick(page, 'glass')
  await expect(page.getByRole('dialog')).toHaveCSS('--bing-image-preview-glass-blur', '0px')
  await expect(page.getByRole('dialog')).toHaveCSS('--bing-image-preview-glass-opacity', '1')
