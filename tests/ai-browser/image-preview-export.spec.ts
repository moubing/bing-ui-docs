import { expect, test, type Page, type Route } from '@playwright/test'

const svg = '<svg xmlns="http://www.w3.org/2000/svg" width="80" height="50"><rect width="80" height="50" fill="skyblue"/></svg>'
const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => {
  const messages: string[] = []; errors.set(page, messages)
  page.on('pageerror', error => messages.push(error.message))
  await page.emulateMedia({ reducedMotion: 'reduce' })
})
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))
const counter = (page: Page) => page.locator('.bing-image-preview__counter')
const media = (page: Page) => page.locator('.bing-image-preview__img')
const businessClick = (page: Page, id: string) => page.locator('#' + id).evaluate((node: HTMLElement) => node.click())
async function reading(page: Page) {
  await page.route('**/preview-fixture/*', route => route.fulfill(route.request().url().endsWith('/broken.svg') ? { status: 404, body: 'missing' } : { status: 200, contentType: 'image/svg+xml', body: svg }))
  await page.goto('/?understanding=image-preview')
}

test('ImagePreview 导出基础：打开、缩放旋转拖动、重置与恢复焦点', async ({ page }) => {
  await page.goto('/?component=image-preview&example=basic')
  const entry = page.getByRole('button', { name: '打开预览', exact: true })
  await entry.click()
  await expect(page.getByRole('dialog', { name: '图片预览', exact: true })).toBeFocused()
  await expect(counter(page)).toHaveAttribute('aria-label', '第 1 张，共 3 张')
  await expect.poll(() => media(page).evaluate((node: HTMLImageElement) => node.naturalWidth)).toBe(900)
  await page.getByRole('button', { name: '放大', exact: true }).click()
  await expect(media(page)).toHaveCSS('transform', 'matrix(1.25, 0, 0, 1.25, 0, 0)')
  await page.getByRole('button', { name: '向右旋转', exact: true }).click()
  await expect(media(page)).toHaveCSS('transform', 'matrix(0, 1.25, -1.25, 0, 0, 0)')
  await page.keyboard.press('0')
  await expect(media(page)).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
  const box = await media(page).boundingBox(); expect(box).not.toBeNull()
  await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2)
  await page.mouse.down(); await page.mouse.move(box!.x + box!.width / 2 + 40, box!.y + box!.height / 2 + 25); await page.mouse.up()
  await expect(media(page)).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 40, 25)')
  await page.getByRole('button', { name: '重置图片', exact: true }).click()
  await expect(media(page)).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(entry).toBeFocused()
})

