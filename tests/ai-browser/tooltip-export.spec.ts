test('Tooltip 导出定位：四个锚点共用一个浮层', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/?component=tooltip&example=placement')
  for (const [label, direction] of [['上方', 'top'], ['右侧', 'right'], ['下方', 'bottom'], ['左侧', 'left']]) {
    const anchor = page.getByRole('button', { name: label!, exact: true })
    await anchor.click()
    await expect(page.getByRole('tooltip')).toHaveCount(1)
    await expect(page.getByRole('tooltip')).toHaveAttribute('id', 'placement-' + direction)
    await expect(anchor).toHaveAttribute('aria-describedby', 'placement-' + direction)
    const box = (await page.getByRole('tooltip').boundingBox())!
    expect(box.x).toBeGreaterThanOrEqual(12)
    expect(box.y).toBeGreaterThanOrEqual(12)
  }
})

test('Tooltip 导出方法：手动切换、重新定位与 Escape', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/?component=tooltip&example=manual')
  await page.getByRole('button', { name: '打开', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('已打开；打开：manual')
  const initial = (await page.getByRole('tooltip').boundingBox())!
  await page.getByRole('button', { name: '移动并重新定位', exact: true }).click()
  await expect.poll(async () => Math.round((await page.getByRole('tooltip').boundingBox())!.x - initial.x)).toBe(40)
  await page.getByRole('button', { name: '切换', exact: true }).click()
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await page.getByRole('button', { name: '打开', exact: true }).click()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await page.getByRole('button', { name: '打开', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('status')).toHaveText('已关闭；关闭：escape')
})

test('Tooltip 阅读应用：受控同步、共享可见性与禁用后恢复', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/?understanding=tooltip')
  await page.getByRole('button', { name: '未同步锚点', exact: true }).click()
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await expect(page.locator('#state')).toContainText('request:true')
  await page.getByRole('button', { name: '显示 A', exact: true }).click()
  await expect(page.locator('#first-visible')).toHaveText('A 实际显示：true')
  await page.getByRole('button', { name: '显示 B', exact: true }).click()
  await expect(page.getByRole('tooltip')).toHaveText('第二条内容')
  await expect(page.locator('#first-visible')).toHaveText('A 实际显示：false')
  await expect(page.locator('#state')).toContainText('"firstOpen":false,"secondOpen":true')
  await expect(page.locator('#state')).toContainText('A-close:replaced')
  await page.getByRole('button', { name: '显示 A', exact: true }).click()
  await page.getByRole('button', { name: '切换 A 禁用', exact: true }).click()
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await expect(page.locator('#state')).toContainText('"firstOpen":true')
  await expect(page.locator('#state')).toContainText('A-close:disabled')
  await page.getByRole('button', { name: '切换 A 禁用', exact: true }).click()
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await page.getByRole('button', { name: '显示 A', exact: true }).click()
  await expect(page.getByRole('tooltip')).toHaveText('第一条内容')
})

test('Tooltip 阅读应用：悬停取消、延迟关闭与聚焦打开', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/?understanding=tooltip')
  await page.clock.install()
  const anchor = page.getByRole('button', { name: '焦点锚点', exact: true })
  await anchor.hover()
  await page.clock.runFor(70)
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await page.mouse.move(1000, 650)
  await page.clock.runFor(250)
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await anchor.hover()
  await page.clock.runFor(250)
  await expect(page.getByRole('tooltip')).toBeVisible()
  await page.mouse.move(1000, 650)
  await page.clock.runFor(30)
  await expect(page.getByRole('tooltip')).toBeVisible()
  await page.clock.runFor(150)
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await page.keyboard.press('Tab')
  await anchor.focus()
  await page.clock.runFor(250)
  await expect(page.getByRole('tooltip')).toHaveText('焦点和悬停提示')
  await expect(anchor).toHaveAttribute('aria-describedby', 'hover-tip')
  await expect(page.locator('#state')).toContainText('hover-open:focus')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('tooltip')).toHaveCount(0)
})

test('Tooltip 阅读应用：窄屏贴顶时翻转，保持视口边距', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 700 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/?understanding=tooltip')
  await page.getByRole('button', { name: '边缘锚点', exact: true }).click()
  await expect(page.getByRole('tooltip')).toHaveClass(/is-placement-bottom/)
  const box = (await page.getByRole('tooltip').boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(12)
  // 位置按设备像素取整，允许最多半个设备像素的舍入差。
  const rounding = 0.5 / await page.evaluate(() => devicePixelRatio)
  expect(box.x + box.width).toBeLessThanOrEqual(378 + rounding)
  expect(box.y).toBeGreaterThanOrEqual(12)
})
