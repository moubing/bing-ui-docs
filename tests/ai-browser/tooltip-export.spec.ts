import { expect, test, type Page } from '@playwright/test'

const errors = new WeakMap<Page, string[]>()
test.beforeEach(({ page }) => { const messages: string[] = []; errors.set(page, messages); page.on('pageerror', error => messages.push(error.message)) })
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))

test('Tooltip 与 Dialog：共享浮层内可点击，Escape 不关闭下层弹窗', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/?understanding=tooltip&composition=1')
  const opener = page.getByRole('button', { name: '打开提示弹窗', exact: true })
  await opener.click()
  const anchor = page.getByRole('button', { name: '查看字段说明', exact: true })
  await anchor.click()
  await expect(anchor).toHaveAttribute('aria-describedby', 'dialog-tip')
  await page.getByRole('tooltip').getByRole('button', { name: '我已阅读', exact: true }).click()
  await expect(page.locator('#dialog-reads')).toHaveText('阅读次数：1')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await expect(page.getByRole('dialog', { name: '提示组合', exact: true })).toBeVisible()
  await anchor.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(opener).toBeFocused()
})

test('Tooltip 导出基础：短提示高度、点击、Escape、外部关闭和按钮提示关联', async ({ page }) => {
  await page.goto('/?component=tooltip&example=basic')
  const button = page.getByRole('button', { name: '查看提示', exact: true })
  await button.click()
  await expect(page.getByRole('tooltip')).toHaveText('斜体')
  await expect.poll(() => page.getByRole('tooltip').evaluate(node => node.getBoundingClientRect().height)).toBe(32)
  await expect(button).toHaveAttribute('aria-describedby', 'basic-tooltip')
  await expect(button).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await expect(page.getByRole('status')).toHaveText('已关闭；关闭：escape')
  await button.click()
  await button.click()
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await expect(page.getByRole('status')).toHaveText('已关闭；关闭：click')
  await expect(button).not.toHaveAttribute('aria-describedby')
})

