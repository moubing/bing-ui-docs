import { expect, test, type Page } from '@playwright/test'

const errors = new WeakMap<Page, string[]>()
test.beforeEach(({ page }) => {
  const messages: string[] = []
  errors.set(page, messages)
  page.on('pageerror', error => messages.push(error.message))
  page.on('console', message => {
    if (/failed to resolve component|unhandled error/i.test(message.text())) messages.push(message.text())
  })
})
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))

test('CheckboxGroup 阅读应用：自动 ID/name 隔离，整组禁用优先于子项 false', async ({ page }) => {
  await page.goto('/?understanding=checkbox-group')
  const ids = await page.locator('[role="group"], input[type="checkbox"]').evaluateAll(nodes => nodes.map(node => node.id))
  expect(ids.every(Boolean)).toBe(true)
  expect(new Set(ids).size).toBe(ids.length)
  const names = await page.getByRole('group').evaluateAll(nodes => nodes.map(node => node.querySelector('input')?.name))
  expect(names.every(Boolean)).toBe(true)
  expect(new Set(names).size).toBe(2)
  await page.getByRole('checkbox', { name: '版本发布', exact: true }).locator('..').click()
  await expect(page.getByRole('status')).toHaveText('渠道：email；内容：docs,release')
  const email = page.getByRole('checkbox', { name: '邮件', exact: true })
  await page.getByRole('button', { name: '切换整组禁用', exact: true }).click()
  await expect(email).toBeDisabled()
  await expect(page.getByRole('checkbox', { name: '版本发布', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '切换整组禁用', exact: true }).click()
  await expect(email).toBeEnabled()
  await expect(page.getByRole('checkbox', { name: '短信', exact: true })).toBeDisabled()
})

test('CheckboxGroup 导出基础和配置：完整数组更新、全选跳过禁用项与清空', async ({ page }) => {
  await page.goto('/?component=checkbox-group&example=basic')
  const group = page.getByRole('group', { name: '功能开关选项', exact: true })
  await expect(group.locator('input:checked')).toHaveCount(2)
  await page.getByRole('button', { name: '全选可用项', exact: true }).click()
  await expect(group.locator('input:checked')).toHaveCount(3)
  await expect(group.getByRole('checkbox', { name: /^实验功能/ })).not.toBeChecked()
  await expect(group.getByRole('checkbox', { name: /^实验功能/ })).toBeDisabled()
  await page.getByRole('button', { name: '清空', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('未选择')
  await group.getByRole('checkbox', { name: /^批量操作/ }).focus()
  await group.getByRole('checkbox', { name: /^批量操作/ }).press('Space')
  await expect(page.getByRole('status')).toContainText('batch')
  await page.goto('/?component=checkbox-group&example=options')
  await page.getByRole('checkbox', { name: '示例', exact: true }).locator('..').click()
  await expect(page.getByText('已选择：docs、demo', { exact: true })).toBeVisible()
})

test('CheckboxGroup 导出插槽和状态：插槽替换 options，共享模型，error 不阻止选择', async ({ page }) => {
  await page.goto('/?component=checkbox-group&example=slot')
  await expect(page.getByRole('checkbox')).toHaveCount(3)
  await expect(page.getByText('这项不会显示', { exact: true })).toHaveCount(0)
  await page.getByRole('checkbox', { name: /^API 对齐/ }).locator('..').click()
  await expect(page.getByRole('status')).toContainText('design、api')
  for (const checkbox of await page.getByRole('checkbox').all()) await expect(checkbox).toHaveAttribute('name', 'review-scope')
  await page.goto('/?component=checkbox-group&example=status')
  const group = page.getByRole('group', { name: '发布检查项', exact: true })
  await expect(group).toHaveAttribute('aria-invalid', 'true')
  await expect(group).toHaveAttribute('aria-describedby', 'release-help')
  await group.getByRole('checkbox', { name: '代码生成', exact: true }).locator('..').click()
  await expect(group.locator('input:checked')).toHaveCount(0)
})

test('CheckboxGroup 导出事件：两个 change 参数及整组 focus/blur 边界', async ({ page }) => {
  await page.goto('/?component=checkbox-group&example=events')
  const first = page.getByRole('checkbox', { name: '站内提醒', exact: true })
  const second = page.getByRole('checkbox', { name: '邮件', exact: true })
  await first.focus()
  await expect(page.getByText('进入组：1；离开组：0', { exact: true })).toBeVisible()
  await second.focus()
  await expect(page.getByText('进入组：1；离开组：0', { exact: true })).toBeVisible()
  await second.press('Space')
  await expect(page.getByRole('status')).toHaveText('change：；原始事件：change')
  await page.getByRole('button', { name: '组外按钮', exact: true }).focus()
  await expect(page.getByText('进入组：1；离开组：1', { exact: true })).toBeVisible()
})
