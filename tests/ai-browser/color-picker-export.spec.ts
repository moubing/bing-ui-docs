import { expect, test, type Page } from '@playwright/test'
const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => { const messages: string[] = []; errors.set(page, messages); page.on('pageerror', error => messages.push(error.message)); await page.emulateMedia({ reducedMotion: 'reduce' }) })
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))
const editor = (page: Page) => page.getByRole('textbox', { name: '颜色值', exact: true })

test('ColorPicker、格式 Select 与 Dialog：文本 Escape 结束编辑，浮层逐层关闭', async ({ page }) => {
  await page.goto('/?understanding=color-picker&composition=1')
  await page.getByRole('button', { name: '打开颜色表单', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '颜色组合', exact: true })
  const trigger = page.getByRole('button', { name: '弹窗颜色', exact: true })
  await trigger.click()
  const colorPanel = page.getByRole('dialog', { name: '弹窗颜色', exact: true })
  await expect(colorPanel).toBeVisible()
  const format = page.getByRole('button', { name: '颜色格式', exact: true })
  await format.click()
  await expect(page.getByRole('listbox')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('listbox')).toHaveCount(0)
  await expect(format).toBeFocused()
  await expect(colorPanel).toBeVisible()
  await format.click()
  await page.getByRole('option', { name: 'HSL', exact: true }).click()
  await expect(editor(page)).toHaveValue(/^hsla?\(/)
  await editor(page).press('Escape')
  await expect(editor(page)).not.toBeFocused()
  await expect(colorPanel).toBeVisible()
  await page.getByRole('slider', { name: '颜色饱和度与亮度', exact: true }).press('Escape')
  await expect(colorPanel).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await expect(dialog).toBeVisible()
  await trigger.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button', { name: '打开颜色表单', exact: true })).toBeFocused()
})

