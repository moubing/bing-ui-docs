test('ColorPicker 导出事件：保留 alpha、关闭方法和失败复制', async ({ page }) => {
  await page.addInitScript(() => {
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('复制不可用') } } })
    document.execCommand = () => false
  })
  await page.goto('/?component=color-picker&example=events')
  await page.getByRole('button', { name: '打开面板', exact: true }).click()
  await editor(page).fill('rgba(1, 2, 3, 0.25)'); await editor(page).press('Enter')
  await expect(page.getByRole('status')).toHaveText('change(input)：rgba(1, 2, 3, 0.25)')
  await page.getByRole('button', { name: '复制 HEX', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('copyError：复制不可用')
  await page.getByRole('button', { name: '关闭面板', exact: true }).focus(); await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '事件颜色', exact: true })).toBeFocused()
})

test('ColorPicker 阅读应用：180ms 提交、完整载荷与保留透明度', async ({ page }) => {
  await page.goto('/?understanding=color-picker')
  await page.getByRole('button', { name: '阅读颜色', exact: true }).click()
  await page.clock.install({ time: new Date('2026-07-01T00:00:00Z') })
  await page.clock.pauseAt(new Date('2026-07-01T00:00:01Z'))
  await editor(page).fill('rgba(1, 2, 3, 0.25)')
  await page.clock.fastForward(179)
  await expect(page.getByRole('status')).toHaveText('rgba(10, 20, 30, 0.4)')
  await page.clock.fastForward(2)
  await expect(page.getByRole('status')).toHaveText('rgba(1, 2, 3, 0.25)')
  const payload = JSON.parse(await page.locator('#payload').innerText())
  expect(payload).toMatchObject({ value: '#010203', hex: '#010203', hexAlpha: '#01020340', rgba: 'rgba(1, 2, 3, 0.25)', rgb: { r: 1, g: 2, b: 3, a: 0.25 }, source: 'input' })
  expect(JSON.parse(await page.locator('#events').innerText())).toEqual(['open', 'update:#010203', 'change:input'])
})

test('ColorPicker 阅读应用：模型回传保留面板 alpha，重新挂载依赖已保存的颜色', async ({ page }) => {
  await page.goto('/?understanding=color-picker')
  await page.locator('#preserve').uncheck()
  await page.getByRole('button', { name: '阅读颜色', exact: true }).click()
  await editor(page).fill('rgba(1, 2, 3, 0.25)'); await editor(page).press('Enter')
  await expect(page.getByRole('status')).toHaveText('#010203')
  await expect(page.getByRole('button', { name: '阅读颜色', exact: true })).toContainText('#01020340')
  expect(JSON.parse(await page.locator('#payload').innerText()).rgb.a).toBe(0.25)
  await page.locator('#mounted').click()
  await expect(page.getByRole('button', { name: '阅读颜色', exact: true })).toHaveCount(0)
  await page.locator('#mounted').click()
  await expect(page.getByRole('button', { name: '阅读颜色', exact: true })).toContainText('#010203ff')
})

