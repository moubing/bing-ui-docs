import { expect, test, type Page } from '@playwright/test'

const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => {
  const messages: string[] = []; errors.set(page, messages)
  page.on('pageerror', error => messages.push(error.message))
  await page.emulateMedia({ reducedMotion: 'no-preference' })
})
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))
const root = (page: Page) => page.locator('.bing-animated-text')
const content = (page: Page) => page.locator('.bing-animated-text__content')
const chars = (page: Page) => page.locator('.bing-animated-text__char')

test('AnimatedText 导出基础：完整文字和默认扫光', async ({ page }) => {
  await page.goto('/?component=animated-text&example=basic')
  await expect(root(page)).toHaveText('让文字动起来')
  await expect(root(page)).toHaveAttribute('data-shine-playing', 'true')
  await expect(content(page)).toHaveCSS('background-size', '100% 100%')
  await expect(root(page)).not.toHaveAttribute('tabindex')
})

test('AnimatedText 导出扫光：颜色、方向和减少动态效果', async ({ page }) => {
  await page.goto('/?component=animated-text&example=shine')
  await expect(root(page)).toHaveClass(/shine-direction-left/)
  await expect(root(page)).toHaveCSS('--animated-text-shine-color', '#d4d4d8')
  await expect(root(page)).toHaveCSS('--animated-text-shine-base-color', '#71717a')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(root(page)).toHaveClass(/is-motion-reduced/)
  await expect(root(page)).not.toHaveAttribute('data-shine-playing')
  await page.reload()
  await expect(root(page)).not.toHaveAttribute('data-shine-playing')
  await expect(root(page)).toHaveText('细腻的扫光文字')
})

test('AnimatedText 导出 jump：拆字、悬停和完整一轮', async ({ page }) => {
  await page.goto('/?component=animated-text&example=jump')
  await expect(chars(page)).toHaveCount(9)
  await expect(content(page)).toHaveText('悬停让每个字符跳动')
  await expect(page.locator('.bing-animated-text__jump-layer')).toHaveAttribute('aria-hidden', 'true')
  await expect(page.locator('.bing-animated-text__jump-layer')).toHaveAttribute('inert', '')
  await expect(chars(page).first()).toHaveAttribute('aria-hidden', 'true')
  await expect(root(page)).not.toHaveAttribute('data-jump-playing')
  await root(page).hover()
  await expect(root(page)).toHaveAttribute('data-jump-playing', 'true')
  await expect.poll(() => chars(page).first().evaluate(node => new DOMMatrixReadOnly(getComputedStyle(node).transform).f)).toBeLessThan(0)
  await page.mouse.move(0, 0)
  await expect(root(page)).not.toHaveAttribute('data-jump-playing')
  await expect(chars(page).first()).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 0)')
})

test('AnimatedText 导出禁用：停止扫光，重新启用从头播放', async ({ page }) => {
  await page.goto('/?component=animated-text&example=disabled')
  await expect(root(page)).toHaveAttribute('data-shine-playing', 'true')
  await page.getByRole('checkbox', { name: '禁用扫光', exact: true }).locator('..').click()
  await expect(root(page)).not.toHaveAttribute('data-shine-playing')
  await expect(content(page)).toHaveCSS('background-image', 'none')
  await expect(root(page)).toHaveText('动画可以暂停')
  await page.getByRole('checkbox', { name: '禁用扫光', exact: true }).locator('..').click()
  await expect(root(page)).toHaveAttribute('data-shine-playing', 'true')
})

test('AnimatedText 阅读应用：同一实例更新循环、动态文字和 Unicode 字符', async ({ page }) => {
  await page.goto('/?understanding=animated-text')
  await expect(chars(page)).toHaveCount(3)
  await expect(root(page)).toHaveAttribute('data-jump-playing', 'true')
  const previous = await root(page).elementHandle()
  await page.getByRole('textbox', { name: '阅读文案', exact: true }).fill('新的文字')
  await expect(content(page)).toHaveText('新的文字')
  await expect(chars(page)).toHaveCount(4)
  expect(await previous!.evaluate(node => node.isConnected)).toBe(true)
  await page.locator('#disabled').check()
  await expect(chars(page)).toHaveCount(0)
  await expect(root(page)).not.toHaveAttribute('data-jump-playing')
  await page.locator('#disabled').uncheck()
  await expect(root(page)).toHaveAttribute('data-jump-playing', 'true')
  await page.locator('#none').click()
  await expect(chars(page)).toHaveCount(0)
  await expect(root(page)).toHaveText('新的文字')
})

test('AnimatedText 阅读应用：同一实例禁用 jump 会清理装饰副本', async ({ page }) => {
  await page.goto('/?understanding=animated-text')
  await page.locator('#keyed').uncheck()
  await expect(root(page)).toHaveAttribute('data-jump-playing', 'true')
  const previous = await root(page).elementHandle()
  await page.locator('#disabled').check()
  await expect(root(page)).toHaveClass(/is-disabled/)
  await expect(root(page)).not.toHaveAttribute('data-jump-playing')
  await expect(chars(page)).toHaveCount(0)
  expect(await previous!.evaluate(node => node.isConnected)).toBe(true)
  await page.locator('#keyed').check()
  await expect(chars(page)).toHaveCount(0)
  await expect(root(page)).not.toHaveAttribute('data-jump-playing')
})

test('AnimatedText 阅读应用：once 不响应 hover，shine 延迟与卸载', async ({ page }) => {
  await page.goto('/?understanding=animated-text')
  await page.locator('#once').click()
  await expect(root(page)).toHaveAttribute('data-jump-playing', 'true')
  await expect(root(page)).not.toHaveAttribute('data-jump-playing')
  await root(page).hover()
  await expect(root(page)).not.toHaveAttribute('data-jump-playing')
  await page.locator('#shine').click()
  await expect(root(page)).not.toHaveAttribute('data-shine-playing')
  await root(page).hover()
  await expect(root(page)).toHaveAttribute('data-shine-playing', 'true')
  await expect.poll(() => content(page).evaluate(node => Number((node as HTMLElement).style.getPropertyValue('--animated-text-shine-p'))), { intervals: [16] }).toBeGreaterThan(0)
  await page.mouse.move(0, 0)
  await expect(root(page)).not.toHaveAttribute('data-shine-playing')
  await root(page).hover()
  await expect(root(page)).toHaveAttribute('data-shine-playing', 'true')
  await page.locator('#mounted').uncheck()
  await expect(root(page)).toHaveCount(0)
})

