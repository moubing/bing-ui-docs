test('AnimatedText 阅读应用：中文窄屏换行与动态切换减少动画偏好', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 800 })
  await page.goto('/?understanding=animated-text')
  const message = '这是一段需要在窄屏中自然换行的中文说明文字'
  await page.getByRole('textbox', { name: '阅读文案', exact: true }).fill(message)
  await expect(content(page)).toHaveText(message)
  await expect(root(page)).toHaveAttribute('data-jump-playing', 'true')
  expect(await root(page).evaluate(node => node.getBoundingClientRect().right <= innerWidth)).toBe(true)
  expect(await chars(page).evaluateAll(nodes => new Set(nodes.map(node => Math.round(node.getBoundingClientRect().top / 30))).size)).toBeGreaterThan(1)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(root(page)).not.toHaveAttribute('data-jump-playing')
  await expect(chars(page)).toHaveCount(0)
  await expect(content(page)).toHaveCSS('opacity', '1')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await expect(root(page)).toHaveAttribute('data-jump-playing', 'true')
  await expect(content(page)).toHaveText(message)
})
