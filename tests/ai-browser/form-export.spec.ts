test('Form 默认 auto：失焦报错、修改复查；下一项提示遵循原生 Tab', async ({ page }, info) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 390, height: 850 })
  await page.goto('/?component=form&example=auto-focus')
  const name = page.getByRole('textbox', { name: '姓名', exact: true })
  const email = page.getByRole('textbox', { name: '邮箱', exact: true })
  const hint = page.locator('.bing-form__next-hint')
  await name.fill('A')
  await expect(name).toHaveValue('A')
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(hint).toHaveCount(0)
  await name.press('Tab')
  await expect(email).toBeFocused()
  await expect(page.getByText('姓名至少 2 个字符', { exact: true })).toBeVisible()
  await name.fill('张三')
  await expect(name).not.toHaveAttribute('aria-invalid', 'true')
  await page.getByRole('checkbox', { name: '显示下一项提示（实验性）', exact: true }).locator('..').click()
  await name.focus()
  await expect(hint).toBeVisible()
  await expect(hint).toHaveAttribute('data-target', (await email.getAttribute('id'))!)
  await page.locator('#app').screenshot({ path: info.outputPath('form-auto-hint-390.png') })
  await name.press('Tab')
  await expect(email).toBeFocused()
  await email.fill('hello@example.com')
  await page.getByRole('button', { name: '保存资料', exact: true }).click()
  await expect(page.locator('#app > p[role="status"]')).toHaveText('校验通过，可执行保存')
  await expect(hint).toHaveCount(0)
  await expect(page.getByRole('checkbox', { name: '显示下一项提示（实验性）', exact: true })).not.toBeChecked()
})

test('Form 异步提交：等待时继续编辑，返回后不抢焦点、不写入过期错误', async ({ page }) => {
  await page.goto('/?understanding=form')
  await page.getByRole('button', { name: '提交检查', exact: true }).click()
  const finish = page.getByRole('button', { name: '完成模拟检查', exact: true })
  await expect(finish).toBeVisible()
  const note = page.getByRole('textbox', { name: '说明', exact: true })
  await note.fill('等待时补全说明')
  // 仅结束模拟网络等待，保持用户已移动到的输入焦点。
  await finish.evaluate(button => (button as HTMLButtonElement).click())
  await expect(page.locator('#app > p[role="status"]')).toHaveText('校验失败，未保存')
  await expect(note).toBeFocused()
  await expect(note).not.toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByText('该账号已占用', { exact: true })).toBeVisible()
})

