test('理解迁移用例：按导出文档新写角色多选，只有合法数据才执行保存', async ({ page }) => {
  await page.goto('/?example=understanding')
  const result = page.locator('#app > p[role="status"]')
  const saved = page.locator('#save-count')
  const submit = page.getByRole('button', { name: '保存角色', exact: true })
  const admin = page.getByRole('checkbox', { name: '管理员', exact: true })
  await submit.click()
  await expect(result).toHaveText('校验失败，未保存')
  await expect(saved).toHaveText('0')
  await expect(page.getByText('至少选择一个角色', { exact: true })).toBeVisible()
  await admin.locator('..').click()
  await submit.click()
  await expect(result).toHaveText('已保存：["admin"]')
  await expect(saved).toHaveText('1')
  await admin.locator('..').click()
  await submit.click()
  await expect(result).toHaveText('校验失败，未保存')
  await expect(saved).toHaveText('1')
})
