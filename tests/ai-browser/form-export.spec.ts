import { expect, test, type Page } from '@playwright/test'

const errors = new WeakMap<Page, string[]>()
test.beforeEach(({ page }) => {
  const messages: string[] = []
  errors.set(page, messages)
  page.on('pageerror', error => messages.push(error.message))
  page.on('console', message => {
    if (/failed to resolve component|unhandled error/i.test(message.text())) messages.push(message.text())
  })
})
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))

test('只使用导出的布局代码：阻止失败提交，数组至少一项，合法数据可进入保存分支', async ({ page }) => {
  await page.goto('/?example=layout')
  const result = page.locator('#app > p[role="status"]')
  await page.getByRole('button', { name: '提交', exact: true }).click()
  await expect(result).toHaveText('校验失败，未执行保存')
  await expect(page.getByRole('textbox', { name: '项目名称', exact: true })).toBeFocused()
  await page.getByPlaceholder('例如：组件文档站').fill('导出实验')
  await page.getByRole('button', { name: '选择方向', exact: true }).click()
  await page.getByRole('option', { name: /设计系统/ }).click()
  await page.getByRole('checkbox', { name: '站内消息', exact: true }).locator('..').click()
  await page.getByRole('button', { name: '提交', exact: true }).click()
  await expect(page.getByText('至少选择一个通知渠道', { exact: true })).toBeVisible()
  await expect(result).toHaveText('校验失败，未执行保存')
  await page.getByRole('checkbox', { name: '邮件通知', exact: true }).locator('..').click()
  await page.getByRole('button', { name: '提交', exact: true }).click()
  await expect(result).toContainText('可以保存：')
  await expect(result).toContainText('"channels":["email"]')
})

test('只使用导出的方法代码：异步校验、保留其他错误、清错和恢复初始快照', async ({ page }) => {
  await page.goto('/?example=methods')
  const fields = page.locator('form input')
  await page.getByRole('button', { name: '校验全部', exact: true }).click()
  await expect(page.getByText('这个邮箱已经被占用', { exact: true })).toBeVisible()
  await fields.nth(0).fill('available@example.com')
  await page.getByRole('button', { name: '校验邮箱', exact: true }).click()
  await expect(page.locator('#app > p[role="status"]')).toHaveText('邮箱校验通过')
  await expect(page.getByText('昵称至少需要 3 个字符', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '读取错误', exact: true }).click()
  await expect(page.locator('#app > p[role="status"]')).toContainText('nickname')
  await expect(page.locator('#app > p[role="status"]')).not.toContainText('email')
  await page.getByRole('button', { name: '清空错误', exact: true }).click()
  await expect(page.locator('.bing-form-item__message.is-error')).toHaveCount(0)
  await expect(fields.nth(0)).toHaveValue('available@example.com')
  await fields.nth(1).fill('Alice')
  await page.getByRole('button', { name: '校验全部', exact: true }).click()
  await expect(page.locator('#app > p[role="status"]')).toHaveText('全部字段校验通过')
  await page.getByRole('button', { name: '重置字段', exact: true }).click()
  await expect(fields.nth(0)).toHaveValue('taken@example.com')
  await expect(fields.nth(1)).toHaveValue('Bo')
})

