test('FormItem 导出跨度示例：响应式占列、超出列数限制及 stack 布局', async ({ page }) => {
  for (const name of ['item-span', 'item-clamped']) {
    await page.goto('/?example=' + name)
    for (const [width, columns] of [[390, 1], [900, 2], [1440, 3]]) {
      await page.setViewportSize({ width: width!, height: 900 })
      const notes = page.locator('.bing-form-item').last()
      await expect(notes).toHaveCSS('grid-column-start', 'span ' + columns)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    }
    // 断点取决于 Form 容器，宽屏中的窄表单仍然只占一列。
    await page.locator('form').evaluate(form => { (form as HTMLElement).style.width = '500px' })
    await expect(page.locator('.bing-form-item').last()).toHaveCSS('grid-column-start', 'span 1')
  }
  await page.goto('/?example=item-stack')
  await expect(page.locator('form')).toHaveClass(/bing-form--stack/)
  const boxes = await page.locator('.bing-form-item').evaluateAll(items => items.map(item => {
    const { x, y, width } = item.getBoundingClientRect()
    return { x, y, width }
  }))
  for (const [index, box] of boxes.entries()) {
    expect(box.x).toBe(boxes[0]!.x)
    expect(box.width).toBe(boxes[0]!.width)
    if (index > 0) expect(box.y).toBeGreaterThan(boxes[index - 1]!.y)
  }
  await page.goto('/?example=item-span')
  await page.getByRole('button', { name: '校验布局表单', exact: true }).click()
  await expect(page.locator('#app > p[role="status"]')).toHaveText('布局表单存在错误')
  await page.getByPlaceholder('例如：新增组件文档').fill('布局文档')
  await page.getByPlaceholder('输入负责人').fill('小王')
  await page.getByRole('button', { name: '选择类型', exact: true }).click()
  await page.getByRole('option', { name: /设计系统/ }).click()
  await page.getByRole('button', { name: '校验布局表单', exact: true }).click()
  await expect(page.locator('#app > p[role="status"]')).toHaveText('布局表单通过校验')
})

test('FormItem 导出插槽示例：原生控件的标签、消息关联、失焦校验及禁用', async ({ page }) => {
  await page.goto('/?example=item-slot')
  const control = page.getByRole('textbox', { name: '自定义控件', exact: true })
  const message = page.locator('.bing-form-item__message')
  await expect(control).toHaveAttribute('aria-describedby', (await message.getAttribute('id'))!)
  await page.locator('.bing-form-item__label').click()
  await expect(control).toBeFocused()
  await expect(control).toHaveClass(/custom-input--lg/)
  await expect(control).toHaveClass(/custom-input--default/)
  await control.fill('A')
  await control.blur()
  await expect(control).toHaveAttribute('aria-invalid', 'true')
  await expect(control).toHaveClass(/custom-input--error/)
  await expect(message).toHaveText('自定义字段至少需要 2 个字符')
  await expect(control).toHaveAttribute('aria-describedby', (await message.getAttribute('id'))!)
  await page.getByRole('button', { name: '保存自定义字段', exact: true }).click()
  await expect(page.locator('#app > p[role="status"]')).toHaveText('校验失败，未保存')
  await control.fill('自定义值')
  await control.blur()
  await expect(control).toHaveAttribute('aria-invalid', 'false')
  await page.getByRole('button', { name: '保存自定义字段', exact: true }).click()
  await expect(page.locator('#app > p[role="status"]')).toHaveText('可以保存：自定义值')
  await page.getByRole('checkbox', { name: '禁用自定义字段', exact: true }).check()
  await expect(control).toBeDisabled()
})

test('FormItem 阅读应用：嵌套路径与原生 textarea，隐藏错误仍阻止保存', async ({ page }) => {
  await page.goto('/?example=item-understanding')
  const control = page.getByRole('textbox', { name: '配送备注', exact: true })
  const save = page.getByRole('button', { name: '保存配送备注', exact: true })
  const count = page.locator('#save-count')
  await expect(control).toHaveClass(/note--sm/)
  await save.click()
  await expect(count).toHaveText('0')
  await expect(control).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByText('配送备注至少 5 个字符', { exact: true })).toBeVisible()
  await page.getByRole('checkbox', { name: '显示消息', exact: true }).uncheck()
  await expect(page.locator('.bing-form-item__message-slot')).toHaveCount(0)
  await expect(control).not.toHaveAttribute('aria-describedby')
  await expect(control).toHaveAttribute('aria-invalid', 'true')
  await save.click()
  await expect(count).toHaveText('0')
  await control.fill('请放在门口的柜子里')
  await control.blur()
  await expect(control).toHaveAttribute('aria-invalid', 'false')
  await save.click()
  await expect(count).toHaveText('1')
  await control.fill('')
  await save.click()
  await expect(count).toHaveText('1')
  await expect(page.locator('#app > p[role="status"]')).toHaveText('校验失败，未保存')
  await page.getByRole('checkbox', { name: '禁用备注', exact: true }).check()
  await expect(control).toBeDisabled()
})
