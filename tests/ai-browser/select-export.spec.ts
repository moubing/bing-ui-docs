test('Select 阅读应用：实例 ID、尺寸行高与主题磨砂', async ({ page }) => {
  await page.goto('/?understanding=select')
  const ids: string[] = []
  for (const [size, height, rowHeight] of [['sm', 32, 28], ['md', 36, 32], ['lg', 40, 36]] as const) {
    const trigger = page.getByRole('combobox', { name: `${size} 独立选择器`, exact: true })
    await expect(trigger.locator('xpath=ancestor::div[contains(@class,"bing-select--")][1]')).toHaveCSS('height', `${height}px`)
    const id = (await trigger.getAttribute('aria-controls'))!
    expect(ids).not.toContain(id)
    ids.push(id)
    await trigger.click()
    await expect(page.getByRole('listbox')).toHaveAttribute('id', id)
    await expect(panel(page)).toHaveCSS('--bing-select-default-option-height', `${rowHeight}px`)
    const optionIds = await page.getByRole('option').evaluateAll(nodes => nodes.map(node => node.id))
    expect(new Set(optionIds).size).toBe(optionIds.length)
    await trigger.press('Escape')
    await expect(trigger).toBeFocused()
  }
  await page.getByRole('combobox', { name: 'md 独立选择器', exact: true }).click()
  await expect(panel(page)).toHaveCSS('--bing-select-glass-opacity', /^0?\.86$/)
  await page.evaluate(() => { document.documentElement.dataset.bingTheme = 'dark' })
  await expect(panel(page)).toHaveCSS('--bing-select-glass-opacity', /^0?\.92$/)
  await expect(panel(page)).toHaveCSS('--bing-select-glass-saturation', '1.05')
})

test('Select 阅读应用：弹窗内搜索、选择、Escape 与焦点返回', async ({ page }) => {
  await page.goto('/?understanding=select')
  const opener = page.getByRole('button', { name: '打开组合弹窗', exact: true })
  await opener.click()
  const dialog = page.getByRole('dialog')
  const trigger = page.getByRole('combobox', { name: '弹窗内选择器', exact: true })
  await trigger.click()
  const search = panel(page).getByRole('combobox')
  await expect(search).toBeFocused()
  await search.fill('Alpha 数字')
  await page.getByRole('option', { name: 'Alpha 数字', exact: true }).click()
  await expect(trigger).toContainText('Alpha 数字')
  await trigger.click()
  await search.press('Escape')
  await expect(panel(page)).toHaveCount(0)
  await expect(dialog).toBeVisible()
  await expect(trigger).toBeFocused()
  await trigger.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(opener).toBeFocused()
})
