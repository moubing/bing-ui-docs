import { expect, test, type Page } from '@playwright/test'
const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => { const list: string[] = []; errors.set(page, list); page.on('pageerror', error => list.push(error.message)); await page.emulateMedia({ reducedMotion: 'reduce' }) })
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))
const panel = (page: Page) => page.locator('.bing-select__panel')
test('Select 导出基础：单选与禁用项、空值', async ({ page }) => {
  await page.goto('/?component=select&example=basic')
  await page.getByRole('combobox', { name: '选择城市', exact: true }).click()
  await expect(panel(page).getByRole('combobox')).toHaveCount(0)
  await expect(page.getByRole('option', { name: '北京', exact: true })).toBeDisabled()
  await page.getByRole('option', { name: '成都', exact: true }).click()
  await expect(page.locator('.select-feedback')).toContainText('成都')
  await expect(panel(page)).toHaveCount(0)
  await page.getByRole('button', { name: '清空选择', exact: true }).click()
  await expect(page.locator('.select-feedback')).toContainText('未选择')
})
