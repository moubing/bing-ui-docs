import { expect, test, type Page } from '@playwright/test'
const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => { const messages: string[] = []; errors.set(page, messages); page.on('pageerror', error => messages.push(error.message)); await page.emulateMedia({ reducedMotion: 'reduce' }) })
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))
const panel = (page: Page) => page.locator('.bing-date-picker__panel')
const day = (page: Page, value: number) => panel(page).locator('.bing-date-picker__cell:not(.is-muted)').filter({ hasText: new RegExp('^' + value + '$') })
const time = (page: Page, unit: string, value: number) => panel(page).locator(`[data-time-unit="${unit}"][data-time-value="${value}"]`)

test('DatePicker 与 Dialog：面板获得焦点，Escape 逐层关闭', async ({ page }) => {
  await page.goto('/?understanding=date-picker&composition=1')
  await page.getByRole('button', { name: '打开日期表单', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '日期组合', exact: true })
  const trigger = page.getByRole('button', { name: '弹窗日期', exact: true })
  await trigger.click()
  await expect(panel(page)).toBeFocused()
  await panel(page).press('Escape')
  await expect(panel(page)).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await expect(dialog).toBeVisible()
  await trigger.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button', { name: '打开日期表单', exact: true })).toBeFocused()
})

test('DatePicker 导出基础：单值立即提交和清除', async ({ page }) => {
  await page.goto('/?component=date-picker&example=basic')
  await page.getByRole('button', { name: '选择日期值', exact: true }).click()
  await day(page, 8).click()
  await expect(page.getByRole('status')).toContainText('change："2026-07-08"')
  await expect(panel(page)).toHaveCount(0)
  await page.getByRole('button', { name: '清空已选日期', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('当前值：null')
})

test('DatePicker 导出单值：显示与保存格式、月份年份和日期时间确认', async ({ page }) => {
  await page.goto('/?component=date-picker&example=singles')
  await expect(page.getByRole('button', { name: 'date单值', exact: true })).toContainText('2026年07月01日')
  await page.getByRole('button', { name: 'date单值', exact: true }).click(); await day(page, 19).click()
  await expect(page.getByText('保存值："2026/07/19"', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'month单值', exact: true }).click(); await panel(page).getByRole('button', { name: '10月', exact: true }).click()
  await expect(page.getByRole('button', { name: 'month单值', exact: true })).toContainText('2026-10')
  await page.getByRole('button', { name: 'year单值', exact: true }).click(); await panel(page).getByRole('button', { name: '2027', exact: true }).click()
  await expect(page.getByRole('button', { name: 'year单值', exact: true })).toContainText('2027')
  await page.getByRole('button', { name: 'datetime单值', exact: true }).click(); await time(page, 'hour', 10).click()
  await expect(page.getByRole('button', { name: 'datetime单值', exact: true })).toContainText('09:30:00')
  await panel(page).getByRole('button', { name: '确定', exact: true }).click()
  await expect(page.getByRole('button', { name: 'datetime单值', exact: true })).toContainText('10:30:00')
})

