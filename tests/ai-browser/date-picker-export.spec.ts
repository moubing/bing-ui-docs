test('DatePicker 导出规则：工作日、15 分钟与精确营业边界', async ({ page }) => {
  await page.goto('/?component=date-picker&example=rules')
  await page.getByRole('button', { name: '工作日日期', exact: true }).click()
  await expect(day(page, 4)).toBeDisabled(); await day(page, 9).click()
  await page.getByRole('button', { name: '营业时间', exact: true }).click()
  await expect(time(page, 'hour', 8)).toBeDisabled()
  await expect(panel(page).locator('[data-time-unit="minute"]')).toHaveCount(4)
  await expect(panel(page).locator('[data-time-unit="second"]')).toHaveCount(2)
  await time(page, 'minute', 0).click(); await time(page, 'hour', 18).click()
  await expect(time(page, 'minute', 15)).toBeDisabled()
  await panel(page).getByRole('button', { name: '确定', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('"18:00:00"')
})

