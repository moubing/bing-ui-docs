test('DatePicker 阅读应用：打开后的 disabled 和 clear 不会清理旧面板', async ({ page }) => {
  await page.goto('/?understanding=date-picker')
  await page.getByRole('button', { name: '阅读日期', exact: true }).click()
  await page.locator('#disabled').focus(); await page.keyboard.press('Space')
  await expect(panel(page)).toBeVisible()
  await expect(day(page, 9)).toBeEnabled()
  await day(page, 9).click()
  await expect(page.getByRole('status')).toHaveText('"2026-07-09"')
  await page.locator('#disabled').uncheck()
  await page.locator('#datetime').click()
  await page.getByRole('button', { name: '阅读日期', exact: true }).click()
  await page.locator('#clear').focus(); await page.keyboard.press('Enter')
  await expect(page.getByRole('status')).toHaveText('null')
  await expect(page.locator('#events')).toHaveText('["open","clear","update","change"]')
  await panel(page).getByRole('button', { name: '确定', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('"2026-07-08 09:30:00"')
})

