import { expect, test, type Page } from '@playwright/test'

const errors = new WeakMap<Page, string[]>()
test.beforeEach(({ page }) => {
  const messages: string[] = []
  errors.set(page, messages)
  page.on('pageerror', error => messages.push(error.message))
})
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))

test('Button 繁忙页面示例：反馈使用原生动画且业务操作只执行一次', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/?component=button&example=busy')
  const button = page.getByRole('button', { name: '模拟繁忙页面' })
  await expect(button).toBeVisible()
  const animations = await button.evaluate(element => {
    ;(element as HTMLButtonElement).click()
    return [...document.querySelectorAll('.bing-click-particles__shard')].flatMap(shard => shard.getAnimations()).length
  })
  expect(animations).toBe(12)
  await expect(page.getByRole('status')).toHaveText('接受点击：1；完成计算：1')
  await expect(page.locator('.bing-click-particles')).toHaveCount(0)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await button.click()
  await expect(page.getByRole('status')).toHaveText('接受点击：2；完成计算：2')
  await expect(page.locator('.bing-click-particles')).toHaveCount(0)
})

test('Button 导出外观：基础、七种类型、五档尺寸和圆角、文字动效', async ({ page }) => {
  await page.goto('/?component=button&example=basic')
  await expect(page.getByRole('button', { name: '提交订单', exact: true })).toHaveAttribute('type', 'button')
  await page.goto('/?component=button&example=variants')
  await expect(page.getByRole('button')).toHaveCount(7)
  await expect(page.getByRole('button', { name: 'primary', exact: true })).toHaveClass(/bing-button--text-shine/)
  await expect(page.getByRole('button', { name: 'secondary', exact: true })).not.toHaveClass(/bing-button--text-shine/)
  await page.goto('/?component=button&example=sizes')
  await expect(page.getByRole('button')).toHaveCount(10)
  await expect(page.getByRole('button', { name: 'XL', exact: true })).toHaveClass(/bing-button--xl/)
  await expect(page.getByRole('button', { name: 'full', exact: true })).toHaveClass(/bing-button--rounded-full/)
  await page.goto('/?component=button&example=text-effect')
  const effect = page.getByRole('button', { name: '悬停看看动效', exact: true })
  await expect(effect).toHaveClass(/bing-button--text-jump/)
  await effect.hover()
  await expect(effect.locator('.bing-animated-text__char')).not.toHaveCount(0)
})

test('Button 导出节流：第一次立即执行，第二次拦截，间隔后恢复', async ({ page }) => {
  await page.goto('/?component=button&example=throttle')
  const button = page.getByRole('button', { name: '连续点击试试', exact: true })
  await page.clock.install()
  await button.dblclick({ delay: 50 })
  const feedback = page.locator('p[role="status"]')
  await expect(feedback).toContainText('有效点击：1；被节流：1')
  await expect(feedback).toContainText(/剩余等待：\d+ms/)
  await expect(page.getByRole('button', { name: '加载中', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '不可用', exact: true })).toBeDisabled()
  await page.clock.fastForward(1300)
  await button.click()
  await expect(feedback).toContainText('有效点击：2；被节流：1')
  await expect(page.getByText('第 2 次有效点击已通过节流校验。', { exact: true })).toBeVisible()
})

test('Button 阅读应用：原生表单、插槽、默认不节流和加载状态', async ({ page }) => {
  await page.goto('/?understanding=button')
  const action = page.getByRole('button', { name: '添加条目', exact: true })
  await action.dblclick({ delay: 20 })
  await expect(page.getByRole('status')).toContainText('提交：0；重置：0；普通操作：2；焦点：focus')
  await expect(action.locator('.bing-button__icon--prefix')).toContainText('＋')
  await expect(action.locator('.bing-button__icon--suffix')).toContainText('→')
  await page.getByRole('button', { name: '提交表单', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('提交：1；重置：0；普通操作：2；焦点：blur')
  await page.getByRole('button', { name: '重置表单', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('重置：1')
  await expect(page.getByRole('button', { name: '正在保存', exact: true })).toHaveAttribute('aria-busy', 'true')
  await expect(page.getByRole('button', { name: '正在保存', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '正在保存', exact: true })).toHaveClass(/bing-button--text-jump/)
  await expect(page.getByRole('button', { name: '正在加载设置', exact: true }).locator('.bing-button__spinner')).toBeVisible()
  await expect(page.getByRole('button', { name: '继承表单状态', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '继承表单状态', exact: true })).toHaveClass(/bing-button--sm/)
  await expect(page.getByRole('button', { name: '覆盖表单状态', exact: true })).toBeEnabled()
  await expect(page.getByRole('button', { name: '覆盖表单状态', exact: true })).toHaveClass(/bing-button--lg/)
  await page.getByRole('button', { name: '打开设置', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('普通操作：3')
})
