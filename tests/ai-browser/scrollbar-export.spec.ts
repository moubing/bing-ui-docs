import { expect, test, type Page } from '@playwright/test'
import { verifyZoomedWheel } from '../browser/scrollbar-smooth-check'

const errors = new WeakMap<Page, string[]>()
test.beforeEach(({ page }) => { const messages: string[] = []; errors.set(page, messages); page.on('pageerror', error => messages.push(error.message)) })
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))

test('Scrollbar 导出平滑示例：保留页面缩放后的鼠标惯性', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/?component=scrollbar&example=smooth')
  const viewport = page.getByRole('region', { name: '平滑滚动示例', exact: true })
  await expect(viewport).toBeVisible()
  await verifyZoomedWheel(viewport)
})

test('Scrollbar 导出 viewport：原生编辑、轨道同步和公开方法作用于同一元素', async ({ page }) => {
  await page.goto('/?component=scrollbar&example=viewport')
  const editor = page.getByRole('textbox', { name: '自定义日志编辑器', exact: true })
  await expect(page.getByRole('region')).toHaveCount(0)
  await expect(page.locator('.bing-scrollbar__rail--vertical')).toBeVisible()
  await page.getByRole('button', { name: '滚动到 180', exact: true }).click()
  await expect.poll(() => editor.evaluate(node => node.scrollTop)).toBe(180)
  await editor.fill('abc')
  await editor.press('Home')
  await editor.press('ArrowRight')
  expect(await editor.evaluate((node: HTMLTextAreaElement) => node.selectionStart)).toBe(1)
  await expect(editor).toHaveValue('abc')
  await expect(page.locator('.bing-scrollbar__rail--vertical')).toBeHidden()
  await page.getByRole('checkbox', { name: '只读编辑器', exact: true }).press('Space')
  await expect(page.getByRole('checkbox', { name: '只读编辑器', exact: true })).toBeChecked()
  await expect(editor).toHaveAttribute('readonly')
  await editor.focus()
  await expect(editor).toBeFocused()
  await page.getByRole('button', { name: '追加日志', exact: true }).click()
  await expect(editor).toHaveValue(/追加日志/)
})

test('Scrollbar 导出基础：键盘、原生事件与轨道拖拽', async ({ page }) => {
  await page.goto('/?component=scrollbar&example=basic')
  const viewport = page.getByRole('region', { name: '组件列表', exact: true })
  await expect(viewport).toHaveAttribute('tabindex', '0')
  await viewport.press('ArrowDown')
  await expect.poll(() => viewport.evaluate(node => node.scrollTop)).toBe(50)
  await expect(page.getByRole('status')).toContainText('scrollTop: 50 / scrollLeft: 0')
  const thumb = page.locator('.bing-scrollbar__thumb--vertical')
  const box = (await thumb.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2 + 50, { steps: 5 })
  await page.mouse.up()
  await expect.poll(() => viewport.evaluate(node => node.scrollTop)).toBeGreaterThan(100)
})

test('Scrollbar 导出横向：Shift 滚轮与平滑/原生纵向示例', async ({ page }) => {
  await page.goto('/?component=scrollbar&example=horizontal')
  const viewport = page.getByRole('region', { name: '横向内容', exact: true })
  await expect(viewport).toHaveAttribute('tabindex', '0')
  await viewport.hover()
  await page.keyboard.down('Shift')
  await page.mouse.wheel(0, 120)
  await page.keyboard.up('Shift')
  await expect.poll(() => viewport.evaluate(node => node.scrollLeft)).toBeGreaterThan(0)
  await page.goto('/?component=scrollbar&example=smooth')
  for (const name of ['平滑滚动示例', '原生滚动示例']) {
    const region = page.getByRole('region', { name, exact: true })
    await expect(region).toHaveAttribute('tabindex', '0')
    await region.hover()
    await page.mouse.wheel(0, 120)
    await expect.poll(() => region.evaluate(node => node.scrollTop)).toBeGreaterThan(0)
  }
})

test('Scrollbar 导出方法：数字定位、原生 smooth、追加更新和外部滚轮', async ({ page }) => {
  await page.goto('/?component=scrollbar&example=methods')
  const viewport = page.getByRole('region', { name: '日志列表', exact: true })
  await expect(viewport).toHaveAttribute('tabindex', '0')
  await page.getByRole('button', { name: '下移 120', exact: true }).click()
  await expect.poll(() => viewport.evaluate(node => node.scrollTop)).toBe(120)
  await page.getByRole('button', { name: '底部', exact: true }).click()
  await expect.poll(() => viewport.evaluate(node => node.scrollHeight - node.clientHeight - node.scrollTop)).toBeLessThan(1)
  await page.getByRole('button', { name: '追加并更新', exact: true }).click()
  await expect(viewport.locator('.logs p')).toHaveCount(46)
  await page.getByRole('button', { name: '顶部', exact: true }).click()
  await expect.poll(() => viewport.evaluate(node => node.scrollTop)).toBe(0)
  await page.locator('.forward').hover()
  await page.mouse.wheel(0, 120)
  await expect(page.getByRole('status')).toHaveText('外部滚轮消费：true')
  await expect.poll(() => viewport.evaluate(node => node.scrollTop)).toBeGreaterThan(0)
})

test('Scrollbar 导出 stop：取消组件自己的插值', async ({ page }) => {
  await page.goto('/?component=scrollbar&example=methods')
  const viewport = page.getByRole('region', { name: '日志列表', exact: true })
  await expect(viewport).toHaveAttribute('tabindex', '0')
  await page.clock.install()
  await viewport.hover()
  await page.mouse.wheel(0, 120)
  await page.clock.runFor(100)
  const before = await viewport.evaluate(node => node.scrollTop)
  expect(before).toBeGreaterThan(0)
  expect(before).toBeLessThan(100)
  await page.getByRole('button', { name: '停止组件插值', exact: true }).click()
  const stopped = await viewport.evaluate(node => node.scrollTop)
  await page.clock.runFor(500)
  expect(await viewport.evaluate(node => node.scrollTop)).toBe(stopped)
})

test('Scrollbar 阅读应用：无轨道仍原生滚动、无溢出的标签和禁用时的程序定位', async ({ page }) => {
  await page.goto('/?understanding=scrollbar')
  const hidden = page.getByRole('region', { name: '关闭轨道的区域', exact: true })
  await expect(hidden).not.toHaveAttribute('tabindex')
  await expect(hidden.locator('..').locator('.bing-scrollbar__rail--vertical')).toBeHidden()
  await hidden.hover()
  await page.mouse.wheel(0, 120)
  await expect.poll(() => hidden.evaluate(node => node.scrollTop)).toBeGreaterThan(0)
  const short = page.getByRole('region', { name: '短内容区域', exact: true })
  await expect(short).toBeVisible()
  await expect(short).not.toHaveAttribute('tabindex')
  const disabled = page.getByRole('region', { name: '禁用区域', exact: true })
  await expect(disabled).toHaveCSS('overflow-y', 'hidden')
  await page.getByRole('button', { name: '程序滚动禁用区域', exact: true }).click()
  await expect.poll(() => disabled.evaluate(node => node.scrollTop)).toBe(100)
})
