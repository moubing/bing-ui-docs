import { expect, test, type Page, type Route } from '@playwright/test'

const svg = '<svg xmlns="http://www.w3.org/2000/svg" width="80" height="50"><rect width="80" height="50" fill="skyblue"/></svg>'
const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => {
  const messages: string[] = []; errors.set(page, messages)
  page.on('pageerror', error => messages.push(error.message))
  await page.emulateMedia({ reducedMotion: 'reduce' })
})
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))

test('Image 导出基础：完整内置图片、原始尺寸和键盘预览', async ({ page }) => {
  await page.goto('/?component=image&example=basic')
  await expect(page.getByRole('status')).toHaveText('状态：loaded；原始尺寸：900 × 560')
  const entry = page.getByRole('button', { name: '预览组件封面图', exact: true })
  await expect(entry).toHaveAttribute('tabindex', '0')
  await expect(entry).toHaveCSS('aspect-ratio', '16 / 9')
  await expect(entry.locator('img.bing-image__img')).toHaveCSS('object-fit', 'cover')
  await entry.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

