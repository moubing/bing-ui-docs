test('Image 阅读应用：idle、加载插槽开关与 srcset 的真实地址', async ({ page }) => {
  let pending: Route | undefined
  await page.route('**/image-fixture/*', route => { pending = route })
  await page.goto('/?understanding=image')
  await expect(page.locator('#state')).toContainText('"events":[]')
  await expect(page.locator('#custom-placeholder')).toHaveText('占位内容')
  await expect(page.locator('#custom-loading')).toHaveCount(0)
  await expect(page.locator('img.bing-image__img')).toHaveCount(0)
  await page.getByRole('button', { name: '加载主图', exact: true }).click()
  await expect.poll(() => pending?.request().url()).toContain('/image-fixture/candidate.svg')
  await expect(page.locator('.bing-image')).toHaveAttribute('aria-busy', 'true')
  await expect(page.locator('#custom-loading')).toHaveText('加载内容')
  await page.getByRole('checkbox', { name: '显示 loading', exact: true }).uncheck()
  await expect(page.locator('#custom-loading')).toHaveCount(0)
  await expect(page.locator('#state')).toContainText('"events":["loading"]')
  const img = page.locator('img.bing-image__img')
  await expect(img).toHaveAttribute('width', '320')
  await expect(img).not.toHaveAttribute('height')
  await expect(img).toHaveAttribute('fetchpriority', 'high')
  await expect(img).toHaveAttribute('crossorigin', 'anonymous')
  await expect(img).toHaveAttribute('referrerpolicy', 'no-referrer')
  await pending!.fulfill({ status: 200, contentType: 'image/svg+xml', body: svg })
  await expect(page.locator('#state')).toContainText('"events":["loading","loaded"]')
  await expect(page.locator('#state')).toContainText('"src":"/image-fixture/primary.svg"')
  await expect(page.locator('#state')).toContainText('/image-fixture/candidate.svg')
  await expect(page.locator('#state')).toContainText('"width":80,"height":50')
  await expect(page.locator('#custom-placeholder')).toHaveCount(0)
  await page.getByRole('button', { name: '清空地址', exact: true }).click()
  await expect(page.locator('#state')).toContainText('"loading","loaded","idle"')
})

test('Image 阅读应用：两次失败、错误插槽开关、重试回到主图', async ({ page }) => {
  const requests: string[] = []
  await page.route('**/image-fixture/*', async route => {
    const path = new URL(route.request().url()).pathname; requests.push(path)
    await route.fulfill(path.endsWith('/recovered.svg') ? { status: 200, contentType: 'image/svg+xml', body: svg } : { status: 404, body: 'missing' })
  })
  await page.goto('/?understanding=image')
  await page.getByRole('button', { name: '加载主图', exact: true }).click()
  await expect(page.locator('#state')).toContainText('"errors":[false,true]')
  await expect(page.locator('#state')).toContainText('"events":["loading","error"]')
  await expect(page.locator('img.bing-image__img')).not.toHaveAttribute('srcset')
  await expect(page.locator('img.bing-image__img')).not.toHaveAttribute('sizes')
  await expect(page.locator('#custom-placeholder')).toHaveText('占位内容')
  await page.getByRole('checkbox', { name: '显示 error', exact: true }).uncheck()
  await expect(page.locator('#retry-image')).toHaveCount(0)
  await expect(page.locator('.bing-image')).toHaveClass(/is-error/)
  await page.getByRole('checkbox', { name: '显示 error', exact: true }).check()
  await page.getByRole('button', { name: '更换回退地址', exact: true }).click()
  await expect(page.locator('.bing-image')).toHaveClass(/is-error/)
  expect(requests).toEqual(['/image-fixture/candidate.svg', '/image-fixture/fallback.svg'])
  await page.getByRole('button', { name: '重试原图', exact: true }).click()
  await expect(page.locator('.bing-image')).toHaveClass(/is-loaded/)
  await expect(page.locator('#state')).toContainText('"errors":[false,true,false]')
  await expect(page.locator('#state')).toContainText('"events":["loading","error","loading","loaded"]')
  expect(requests.slice(-2)).toEqual(['/image-fixture/candidate.svg', '/image-fixture/recovered.svg'])
})

test('Image 阅读应用：图库优先级、预览载荷与禁用后重新启用', async ({ page }) => {
  await page.route('**/image-fixture/*', route => route.fulfill({ status: 200, contentType: 'image/svg+xml', body: svg }))
  await page.goto('/?understanding=image')
  await expect(page.getByRole('button', { name: '阅读图片预览', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '加载主图', exact: true }).click()
  await page.getByRole('button', { name: '阅读图片预览', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.locator('.bing-image-preview__stage img')).toHaveAttribute('src', '/image-fixture/gallery.svg')
  await expect(page.locator('#state')).toContainText('open:/image-fixture/single.svg')
  // 模拟业务在预览开启期间修改配置，使用已有 checkbox 的真实 DOM click。
  await page.locator('#preview-enabled').evaluate((node: HTMLInputElement) => node.click())
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('#state')).not.toContainText('close:')
  await page.locator('#preview-enabled').check()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('#state')).toContainText('close:escape')
})
