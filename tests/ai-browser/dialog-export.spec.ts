test('Dialog 导出基础：默认确认保留、取消关闭遮罩和 Escape 与滚动恢复', async ({ page }) => {
  await page.goto('/?component=dialog&example=basic')
  const initial = await page.evaluate(() => document.body.style.overflow)
  const launch = page.getByRole('button', { name: '打开弹窗', exact: true })
  await launch.click()
  await expect(page.getByRole('dialog', { name: '发布组件文档', exact: true })).toBeVisible()
  await expect(page.locator('.bing-dialog__orb')).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => document.body.style.overflow)).toBe('hidden')
  await page.getByRole('button', { name: '确认发布', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('confirm：1')
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: '稍后', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('status')).toContainText('最后关闭：cancel；confirm：1；cancel：1')
  for (const reason of ['close', 'escape', 'overlay']) {
    await launch.click()
    await expect(page.getByRole('dialog')).toBeVisible()
    if (reason === 'close') await page.getByRole('button', { name: '关闭弹窗', exact: true }).click()
    else if (reason === 'escape') await page.keyboard.press('Escape')
    else await page.locator('.bing-dialog__overlay').click({ position: { x: 5, y: 5 } })
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.getByRole('status')).toContainText('最后关闭：' + reason)
  }
  await expect.poll(() => page.evaluate(() => document.body.style.overflow)).toBe(initial)
})

