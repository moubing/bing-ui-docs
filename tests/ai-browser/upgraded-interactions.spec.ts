import { expect, test } from '@playwright/test'

test('文字切换：计数、上传和按钮文案收敛到最后一次操作', async ({ page }) => {
  await page.goto('/?component=animated-text&example=motion')
  for (let i = 0; i < 5; i++) await page.getByRole('button', { name: '增加未读', exact: true }).click()
  await expect(page.getByRole('status').first()).toHaveText('20 条未读消息')
  await page.getByRole('button', { name: '模拟上传', exact: true }).click()
  await page.getByRole('button', { name: '模拟上传', exact: true }).click()
  await expect(page.getByRole('status').last()).toHaveText('2 个文件已上传')
  await expect(page.locator('[data-swapping]')).toHaveCount(0)
  const manual = page.getByRole('button', { name: '悬停、聚焦或点击播放', exact: true })
  await manual.hover({ position: { x: 5, y: 5 } })
  await expect(manual.locator('.bing-animated-text')).toHaveAttribute('data-jump-playing', 'true')
  await page.goto('/?component=button&example=swap')
  await page.getByRole('button', { name: '复制链接', exact: true }).click()
  await expect(page.getByRole('button', { name: '已复制', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '关注', exact: true }).click()
  await expect(page.getByRole('button', { name: '已关注', exact: true })).toBeVisible()
  const whole = page.getByRole('button', { name: '整个按钮都能感应', exact: true })
  await whole.hover({ position: { x: 5, y: 5 } })
  await expect(whole.locator('.bing-animated-text')).toHaveAttribute('data-jump-playing', 'true')
})

test('Checkbox：半选、连点和禁用项保持正确终态', async ({ page }) => {
  await page.goto('/?component=checkbox&example=interaction')
  const all = page.getByRole('checkbox', { name: '全选任务', exact: true })
  await expect(all).toHaveJSProperty('indeterminate', true)
  await all.locator('..').click()
  await expect(page.getByRole('status')).toHaveText('已选 3 / 3')
  for (let i = 0; i < 3; i++) await all.locator('..').click()
  await expect(page.getByRole('status')).toHaveText('已选 0 / 3')
  await expect(page.getByRole('checkbox', { name: '不可修改的任务', exact: true })).toBeChecked()
})

test('CheckboxGroup：Shift 跳过禁用项，刷选只提交一次 change', async ({ page }) => {
  await page.goto('/?component=checkbox-group&example=batch')
  const first = page.getByRole('checkbox', { name: '设计', exact: true }).locator('..')
  const last = page.getByRole('checkbox', { name: '发布', exact: true }).locator('..')
  await first.click()
  await last.click({ modifiers: ['Shift'] })
  await expect(page.getByRole('status')).toHaveText('已选：1, 2, 4, 5；change：2')
  await expect(page.getByRole('checkbox', { name: '已归档（禁用）', exact: true })).not.toBeChecked()
  await page.reload()
  const a = (await first.boundingBox())!, b = (await last.boundingBox())!
  await page.mouse.move(a.x + 8, a.y + a.height / 2)
  await page.mouse.down()
  await page.mouse.move(b.x + 8, b.y + b.height / 2, { steps: 28 })
  await page.mouse.up()
  await expect(page.getByRole('status')).toHaveText('已选：1, 2, 4, 5；change：1')
})

test('Dialog：初始表单焦点、busy 和异步关闭检查', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/?component=dialog&example=guard')
  const opener = page.getByRole('button', { name: '打开关闭拦截示例', exact: true })
  await opener.click()
  await expect(page.getByRole('textbox', { name: '草稿名称', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.locator('[role=status]')).toHaveText('上次拦截：escape')
  await page.getByRole('checkbox', { name: '允许关闭', exact: true }).locator('..').click()
  await page.getByRole('checkbox', { name: '模拟忙碌', exact: true }).locator('..').click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: '取消', exact: true })).toBeDisabled()
  await page.getByRole('checkbox', { name: '模拟忙碌', exact: true }).locator('..').click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(opener).toBeFocused()
})

test('DropDown：分组、勾选、前缀匹配及 Tab 关闭', async ({ page }) => {
  await page.goto('/?component=drop-down&example=selection')
  await page.getByRole('button', { name: '视图设置', exact: true }).press('ArrowDown')
  await expect(page.getByRole('group', { name: '排列方式', exact: true })).toBeVisible()
  await expect(page.getByRole('menuitemradio', { name: '列表', exact: true })).toBeFocused()
  await page.keyboard.press('k')
  const board = page.getByRole('menuitemradio', { name: '看板', exact: true })
  await expect(board).toBeFocused()
  await board.press('Enter')
  await expect(board).toHaveAttribute('aria-checked', 'true')
  await page.getByRole('menuitemcheckbox', { name: '显示归档', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('看板；归档：显示')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('menu')).toHaveCount(0)
})

test('Tooltip：键盘、快捷键、禁用包装和菜单展开抑制', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/?component=tooltip&example=toolbar')
  const bold = page.getByRole('button', { name: '加粗', exact: true })
  await expect(bold).toBeVisible()
  await page.keyboard.press('Tab')
  await expect(bold).toBeFocused()
  await expect(page.getByRole('tooltip')).toBeVisible()
  await expect(bold).toHaveAttribute('aria-keyshortcuts', 'Control+B')
  await expect(bold).not.toHaveAttribute('aria-describedby')
  await expect(page.getByRole('tooltip')).toHaveClass(/is-tone-inverse/)
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: '斜体', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('tooltip')).toContainText('需要先选择文档')
  const more = page.getByRole('button', { name: '更多', exact: true })
  await more.hover()
  await expect(page.getByRole('tooltip')).toContainText('更多操作')
  await more.click()
  await expect(more).toHaveAttribute('aria-expanded', 'true')
  await expect(page.getByRole('menu')).toBeVisible()
  await expect(page.getByRole('tooltip')).toHaveCount(0)
})

for (const theme of ['light', 'dark']) {
  test(`新增示例：420px 高视口、${theme} 主题和减少动态效果`, async ({ page }, info) => {
    await page.setViewportSize({ width: 390, height: 420 })
    await page.emulateMedia({ reducedMotion: 'reduce', colorScheme: theme === 'dark' ? 'dark' : 'light' })
    for (const [component, example] of [['animated-text', 'motion'], ['button', 'swap'], ['checkbox', 'interaction'], ['checkbox-group', 'batch'], ['dialog', 'guard'], ['drop-down', 'selection'], ['tooltip', 'toolbar']]) {
      await page.goto(`/?component=${component}&example=${example}`)
      await page.locator('html').evaluate((node, value) => node.setAttribute('data-bing-theme', value), theme)
      await expect(page.locator('#app')).not.toBeEmpty()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      if (component === 'dialog') await page.getByRole('button', { name: '打开关闭拦截示例', exact: true }).click()
      if (component === 'drop-down') await page.getByRole('button', { name: '视图设置', exact: true }).click()
      if (component === 'tooltip') await page.getByRole('button', { name: '加粗', exact: true }).hover()
      const panel = page.locator('[role=dialog], [role=menu], [role=tooltip]').first()
      if (['dialog', 'drop-down', 'tooltip'].includes(component!)) {
        await expect(panel).toBeVisible()
        const box = (await panel.boundingBox())!
        expect(box.x).toBeGreaterThanOrEqual(0)
        expect(box.y).toBeGreaterThanOrEqual(0)
        expect(box.x + box.width).toBeLessThanOrEqual(390.5)
        expect(box.y + box.height).toBeLessThanOrEqual(420.5)
      }
      await page.screenshot({ path: info.outputPath(`${component}-${theme}-390.png`), animations: 'disabled' })
    }
  })
}
