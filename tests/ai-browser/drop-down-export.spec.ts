import { expect, test, type Page } from '@playwright/test'

const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => {
  const messages: string[] = []; errors.set(page, messages)
  page.on('pageerror', error => messages.push(error.message))
  await page.emulateMedia({ reducedMotion: 'reduce' })
})
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))

test('DropDown 导出定位：右侧按钮在宽窄屏和尺寸变化后保持 bottom-end 对齐', async ({ page }) => {
  await page.goto('/?component=drop-down&example=basic')
  await page.getByRole('button', { name: '打开菜单', exact: true }).click()
  const menu = page.getByRole('menu', { name: '文档操作', exact: true })
  const trigger = page.getByRole('button', { name: '关闭菜单', exact: true })
  await expect(menu).toBeVisible()
  for (const width of [1440, 390, 1024]) {
    await page.setViewportSize({ width, height: 900 })
    await expect.poll(async () => {
      const anchor = (await trigger.boundingBox())!, panel = (await menu.boundingBox())!
      return Math.max(Math.abs(panel.x + panel.width - anchor.x - anchor.width), Math.abs(panel.y - anchor.y - anchor.height - 8))
    }).toBeLessThan(1)
  }
})

test('DropDown 导出虚拟锚点：局部边界与长菜单选择', async ({ page }) => {
  await page.goto('/?component=drop-down&example=caret')
  const stage = page.locator('.caret-stage')
  const bounds = (await stage.boundingBox())!
  await stage.click({ position: { x: 32, y: bounds.height - 32 } })
  const menu = page.getByRole('menu', { name: '虚拟锚点菜单' })
  await expect(menu).toBeVisible()
  await expect(menu).toHaveClass(/is-placement-top/)
  await expect.poll(async () => (await menu.boundingBox())!.y).toBeGreaterThanOrEqual(bounds.y)
  await expect.poll(async () => { const rect = (await menu.boundingBox())!; return rect.y + rect.height }).toBeLessThanOrEqual(bounds.y + bounds.height - 31)
  await menu.getByRole('menuitem', { name: /块命令 16/ }).click()
  await expect(page.getByRole('status')).toHaveText('块命令 16')
})

test('DropDown 导出基础：ARIA、键盘边界与本地点击反馈', async ({ page }) => {
  await page.goto('/?component=drop-down&example=basic')
  const trigger = page.getByRole('button', { name: '打开菜单', exact: true })
  await expect(trigger).toHaveAttribute('aria-haspopup', 'menu')
  await trigger.focus()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('menu', { name: '文档操作', exact: true })).toBeVisible()
  await expect(page.getByRole('menuitem', { name: /^新建页面/ })).toBeFocused()
  await page.keyboard.press('End')
  await expect(page.getByRole('menuitem', { name: /^删除草稿/ })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('menuitem', { name: /^新建页面/ })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('menu')).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.getByRole('menuitem', { name: /^重命名/ }).click()
  await expect(page.getByRole('status')).toContainText('点击：重命名 → 菜单已关闭')
  await expect(page.getByRole('menu')).toHaveCount(0)
})

