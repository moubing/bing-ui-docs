import { expect, test, type Page } from '@playwright/test'

const errors = new WeakMap<Page, string[]>()
test.beforeEach(({ page }) => { const messages: string[] = []; errors.set(page, messages); page.on('pageerror', error => messages.push(error.message)) })
test.afterEach(({ page }) => expect(errors.get(page)).toEqual([]))

test('Input 导出：鼠标聚焦首帧即显示平滑光标，按下期间不切回原生光标', async ({ page }) => {
  await page.goto('/?component=input&example=basic')
  const input = page.getByRole('textbox', { name: '基础输入框示例', exact: true })
  await input.evaluate(node => {
    node.addEventListener('focus', () => requestAnimationFrame(() => {
      node.dataset.firstFrameSmooth = String(node.hasAttribute('data-smooth-caret'))
      node.dataset.firstFrameCaretColor = getComputedStyle(node).caretColor
    }), { once: true })
  })
  const box = (await input.boundingBox())!
  await page.mouse.move(box.x + box.width - 20, box.y + box.height / 2)
  await page.mouse.down()
  await expect(input).toHaveAttribute('data-first-frame-smooth', 'true')
  await expect(input).toHaveAttribute('data-first-frame-caret-color', 'rgba(0, 0, 0, 0)')
  await expect(page.locator('.bing-input__caret[data-active]')).toBeVisible()
  await page.mouse.up()
  await input.press('ControlOrMeta+A')
  await expect(input).not.toHaveAttribute('data-smooth-caret')
})

