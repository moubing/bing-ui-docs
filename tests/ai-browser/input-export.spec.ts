test('Input 原生引擎组词：平滑光标、确认一次、取消恢复及英文衔接', async ({ page }) => {
  await page.goto('/?component=input&example=basic')
  const input = page.getByRole('textbox', { name: '基础输入框示例', exact: true })
  await input.fill('ABC')
  const cdp = await page.context().newCDPSession(page)
  for (const text of ['n', 'ni', 'nihao']) {
    await cdp.send('Input.imeSetComposition', { text, selectionStart: text.length, selectionEnd: text.length })
    await expect(input).toHaveValue('ABC' + text)
    await expect(input).toHaveAttribute('data-smooth-caret', '')
    await expect(page.getByRole('status')).toHaveText('当前值：ABC')
  }
  await cdp.send('Input.insertText', { text: '你好' })
  await expect(input).toHaveValue('ABC你好')
  await expect(page.getByRole('status')).toHaveText('当前值：ABC你好')
  await cdp.send('Input.imeSetComposition', { text: 'zhongwen', selectionStart: 0, selectionEnd: 8 })
  await expect(input).toHaveAttribute('data-smooth-caret', '')
  await cdp.send('Input.imeSetComposition', { text: '', selectionStart: 0, selectionEnd: 0 })
  await expect(input).toHaveValue('ABC你好')
  await input.press('End')
  await input.pressSequentially('OK')
  await expect(page.getByRole('status')).toHaveText('当前值：ABC你好OK')
})

test('Input 阅读应用：清除顺序、程序赋值与待发通知、零延迟、卸载取消', async ({ page }) => {
  await page.goto('/?understanding=input')
  const input = page.getByRole('textbox', { name: '查询条件', exact: true })
  await expect(input).toBeVisible()
  await page.clock.install()
  await input.fill('待发值')
  await page.getByRole('button', { name: '程序赋值', exact: true }).click()
  await expect(input).toHaveValue('程序赋值')
  await page.clock.fastForward(600)
  await expect(page.getByRole('status')).toHaveText('["update:待发值","input:待发值","debounced:待发值"]')
  await input.fill('即将清除')
  await page.getByRole('button', { name: '清空输入', exact: true }).click()
  const afterClear = JSON.parse((await page.getByRole('status').textContent())!) as string[]
  expect(afterClear.slice(-5)).toEqual(['update:即将清除', 'input:即将清除', 'update:', 'clear', 'debounced:'])
  await page.clock.fastForward(600)
  await expect(page.getByRole('status')).toHaveText(JSON.stringify(afterClear))
  await page.getByRole('button', { name: '立即通知', exact: true }).click()
  await input.fill('零延迟')
  expect(JSON.parse((await page.getByRole('status').textContent())!).slice(-3)).toEqual(['update:零延迟', 'input:零延迟', 'debounced:零延迟'])
  await page.goto('/?understanding=input')
  await expect(input).toBeVisible()
  await input.fill('卸载前输入')
  await page.getByRole('button', { name: '卸载输入', exact: true }).click()
  await page.clock.fastForward(1000)
  await expect(page.getByRole('status')).toHaveText('["update:卸载前输入","input:卸载前输入"]')
})
