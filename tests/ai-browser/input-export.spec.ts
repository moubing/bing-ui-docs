test('Input 导出：数值类型、小数步进、边界、空值和只读', async ({ page }) => {
  await page.goto('/?component=input&example=number')
  const input = page.getByRole('spinbutton', { name: '数值输入示例', exact: true })
  const root = input.locator('xpath=ancestor::div[contains(@class,"bing-input")][1]')
  await input.fill('0')
  await expect(page.getByRole('status')).toContainText('模型：0；类型：number；input：0 (string)；debounced：0 (string)')
  await root.getByRole('button', { name: '增加数值', exact: true }).click()
  await expect(input).toHaveValue('0.5')
  await input.press('ArrowUp')
  await expect(input).toHaveValue('1')
  await input.fill('10')
  await expect(root.getByRole('button', { name: '增加数值', exact: true })).toBeDisabled()
  await expect(input).toHaveValue('10')
  await input.fill('0')
  await expect(root.getByRole('button', { name: '减少数值', exact: true })).toBeDisabled()
  await expect(input).toHaveValue('0')
  await input.fill('11')
  expect(await input.evaluate((node: HTMLInputElement) => node.validity.rangeOverflow)).toBe(true)
  await root.getByRole('button', { name: '清空输入', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('模型：null；类型：null')
  await page.getByRole('button', { name: '重置为空', exact: true }).click()
  await expect(input).toHaveValue('')
  await expect(page.getByRole('status')).toContainText('模型：null；类型：null')
  await page.getByRole('button', { name: '设为零', exact: true }).click()
  await expect(input).toHaveValue('0')
  const readonly = page.getByRole('spinbutton', { name: '只读数值', exact: true })
  await readonly.focus()
  await readonly.press('ArrowUp')
  await expect(readonly).toHaveValue('3')
  await expect(page.getByRole('button', { name: '增加数值', exact: true }).last()).toBeDisabled()
})

test('Input 导出：只读保留选择、光标开关与减少动态效果', async ({ page }) => {
  await page.goto('/?component=input&example=readonly')
  const input = page.getByRole('textbox', { name: '只读与光标示例', exact: true })
  await input.focus()
  await expect(input).toBeFocused()
  await input.press('ControlOrMeta+A')
  expect(await input.evaluate((node: HTMLInputElement) => node.selectionEnd! - node.selectionStart!)).toBeGreaterThan(0)
  await expect(page.getByRole('button', { name: '清空输入', exact: true })).toHaveCount(0)
  await page.getByRole('checkbox', { name: '只读', exact: true }).locator('..').click()
  await input.fill('光标测试')
  await input.press('End')
  await expect(input).toHaveAttribute('data-smooth-caret', '')
  await page.getByRole('checkbox', { name: '平滑光标', exact: true }).locator('..').click()
  await input.focus()
  await expect(input).not.toHaveAttribute('data-smooth-caret')
  await page.getByRole('checkbox', { name: '平滑光标', exact: true }).locator('..').click()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await input.focus()
  await expect(input).not.toHaveAttribute('data-smooth-caret')
})

test('Input 导出：即时输入参数、防抖、清除与按键', async ({ page }) => {
  await page.goto('/?component=input&example=debounce')
  const input = page.getByRole('searchbox', { name: '防抖搜索', exact: true })
  await expect(input).toBeVisible()
  await page.clock.install()
  await input.fill('abc')
  await expect(page.getByRole('status')).toHaveText('即时：abc:input；防抖：等待输入；清除：0')
  await page.clock.fastForward(600)
  await expect(page.getByRole('status')).toHaveText('即时：abc:input；防抖：abc；清除：0')
  await input.press('ArrowLeft')
  await expect(page.getByText(/按键：ArrowLeft$/)).toBeVisible()
  await page.getByRole('button', { name: '清空输入', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('即时：abc:input；防抖：空字符串；清除：1')
  await expect(input).toBeFocused()
})

