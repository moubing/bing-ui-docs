import { expect, test } from '@playwright/test'
import { componentDocsTests } from './component-docs'

const open = componentDocsTests({ slug: 'textarea', title: 'BingTextarea', ready: '#playground textarea', previews: 6, tables: 3,
  sections: ['overview', 'playground', 'autosize-count', 'resize-status', 'events-demo', 'submit', 'expose', 'props', 'events-expose', 'events', 'expose-list'] })

test('Textarea：高度策略切换、禁用、清除与实际选区', async ({ page }) => {
  await open(page)
  const basic = page.getByRole('textbox', { name: '基础 Textarea 示例', exact: true })
  const original = await basic.elementHandle()
  await basic.focus()
  await expect(basic).toHaveAttribute('data-smooth-caret', '')
  await page.getByRole('checkbox', { name: '平滑光标', exact: true }).locator('..').click()
  await basic.focus()
  await expect(basic).not.toHaveAttribute('data-smooth-caret')
  await expect(page.locator('#playground .bing-code-block__code')).toContainText('"smoothCaret": false')
  await page.getByRole('checkbox', { name: '平滑光标', exact: true }).locator('..').click()
  await basic.focus()
  await expect(basic).toHaveAttribute('data-smooth-caret', '')
  await basic.fill('保留文本\n第二行')
  await page.getByRole('radiogroup', { name: 'Textarea 自动高度', exact: true }).getByRole('radio', { name: /^off/ }).locator('..').click()
  await expect(basic).toHaveValue('保留文本\n第二行')
  await expect.poll(() => basic.evaluate(node => node.style.height)).toBe('')
  expect(await original!.evaluate(node => node.isConnected)).toBe(true)
  await expect(page.locator('#playground .bing-code-block__code')).toContainText('"autosize": false')
  await page.getByRole('checkbox', { name: '只读', exact: true }).locator('..').click()
  await expect(basic).toHaveAttribute('readonly', '')
  await expect(page.locator('#playground .bing-code-block__code')).toContainText('"readonly": true')
  await expect(page.locator('#playground .doc-example__preview').getByRole('button', { name: '清空文本', exact: true })).toHaveCount(0)
  await basic.focus()
  await expect(basic).toBeFocused()
  await page.getByRole('checkbox', { name: '禁用', exact: true }).locator('..').click()
  await expect(basic).toBeDisabled()
  const resize = page.getByRole('textbox', { name: '禁止拖拽', exact: true })
  await resize.fill('可编辑的值')
  await expect(page.locator('#resize-status .bing-textarea').first().getByRole('button', { name: '清空文本', exact: true })).toHaveCount(0)
  await expect(resize).toHaveValue('可编辑的值')
  const event = page.locator('#events-demo textarea')
  await event.fill('abc')
  await expect(page.locator('#events-demo .textarea-feedback')).toContainText('input：3 个字符')
  await page.locator('#events-demo').getByRole('button', { name: '清空文本', exact: true }).click()
  await expect(event).toHaveValue('')
  await expect(page.locator('#events-demo .textarea-feedback')).toContainText('clear：已清空')
  const exposed = page.getByRole('textbox', { name: '实例方法示例', exact: true })
  await page.getByRole('button', { name: 'focus', exact: true }).click()
  await expect(exposed).toBeFocused()
  await page.getByRole('button', { name: 'select', exact: true }).click()
  expect(await exposed.evaluate((node: HTMLTextAreaElement) => [node.selectionStart, node.selectionEnd])).toEqual([0, (await exposed.inputValue()).length])
  await expect(page.locator('#expose .textarea-feedback')).toContainText(await exposed.inputValue())
  await page.getByRole('button', { name: 'blur', exact: true }).click()
  await expect(exposed).not.toBeFocused()
})
