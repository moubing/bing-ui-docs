import { expect, test } from '@playwright/test'
import { componentDocsTests } from './component-docs'

const open = componentDocsTests({ slug: 'config-provider', title: 'BingConfigProvider', ready: '#size .doc-example__preview .bing-input', previews: 3, tables: 6,
  sections: ['overview', 'size', 'z-index', 'motion', 'props', 'slots', 'size-order', 'layers', 'functions', 'types'] })

test('ConfigProvider：全局尺寸、显式优先和嵌套覆盖', async ({ page }) => {
  await open(page)
  const outer = page.locator('#size section[aria-label="外层 Provider"]')
  const inner = page.locator('#size section[aria-label="嵌套 Provider"]')
  await expect(outer.locator('.bing-input')).toHaveClass(/bing-input--lg/)
  await expect(outer.locator('.bing-select')).toHaveClass(/bing-select--lg/)
  await expect(outer.locator('.bing-tag')).toHaveClass(/bing-tag--lg/)
  await expect(outer.getByRole('button', { name: '继承尺寸', exact: true })).toHaveClass(/bing-button--lg/)
  await expect(outer.getByRole('button', { name: '显式 sm', exact: true })).toHaveClass(/bing-button--sm/)
  await expect(inner.locator('.bing-input')).toHaveClass(/bing-input--sm/)
  await page.locator('#size').getByRole('radio', { name: 'md', exact: true }).locator('..').click()
  await expect(outer.locator('.bing-input')).toHaveClass(/bing-input--md/)
  await expect(outer.getByRole('button', { name: '显式 sm', exact: true })).toHaveClass(/bing-button--sm/)
  await expect(inner.locator('.bing-input')).toHaveClass(/bing-input--sm/)
})

test('ConfigProvider：浮层层级基准与第三方挂件', async ({ page }) => {
  await open(page)
  const section = page.locator('#z-index')
  await section.getByRole('button', { name: '打开弹窗', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '确认发布' })).toBeVisible()
  await expect(page.locator('.bing-dialog-root')).toHaveCSS('z-index', '2000')
  await expect(page.getByRole('complementary', { name: '第三方客服挂件' })).toHaveCSS('z-index', '2500')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: '确认发布' })).toBeHidden()
  await expect(page.getByRole('complementary', { name: '第三方客服挂件' })).toHaveCount(0)
  await section.getByRole('radio', { name: /提高到 3000/ }).locator('..').click()
  await expect(section.getByRole('status')).toContainText('当前基准：3000；弹窗 3000，提示 4200')
  await section.getByRole('button', { name: '打开弹窗', exact: true }).click()
  await expect(page.locator('.bing-dialog-root')).toHaveCSS('z-index', '3000')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: '确认发布' })).toBeHidden()
})

test('ConfigProvider：reducedMotion 覆盖系统偏好并即时重建动画', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await open(page)
  const section = page.locator('#motion')
  const text = section.locator('.bing-animated-text.motion-demo__title')
  await expect(text).toHaveAttribute('data-jump-ready', 'true')
  await section.getByRole('radio', { name: /^always/ }).locator('..').click()
  await expect(text).not.toHaveAttribute('data-jump-ready')
  await expect(section.getByRole('status')).toContainText('当前策略：always')
  await section.getByRole('radio', { name: /^user/ }).locator('..').click()
  await expect(text).toHaveAttribute('data-jump-ready', 'true')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(text).not.toHaveAttribute('data-jump-ready')
  await section.getByRole('radio', { name: /^never/ }).locator('..').click()
  await expect(text).toHaveAttribute('data-jump-ready', 'true')
  await expect(text).toContainText('跟随全局动效策略')
})

test('ConfigProvider：共享 Tooltip 分别遵循局部动效策略', async ({ page }, info) => {
  // 此处比较 JS 动效；系统减少动态效果的 CSS 降级不受 Provider 覆盖。
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await open(page)
  const section = page.locator('#motion')
  const panel = page.getByRole('tooltip')
  await section.getByRole('button', { name: '局部完整动效', exact: true }).hover()
  await expect(panel).toHaveText('这个提示始终完整播放动画。')
  await expect(panel).not.toHaveCSS('transform', 'none')
  await panel.evaluate(node => node.setAttribute('data-motion-test', 'shared'))
  await section.getByRole('button', { name: '局部减少动效', exact: true }).hover()
  await expect(panel).toHaveText('这个提示不播放过渡动画。')
  await expect(panel).toHaveAttribute('data-motion-test', 'shared')
  await expect(panel).toHaveCSS('transform', 'none')
  await page.locator('#motion .doc-example').screenshot({ path: info.outputPath('config-provider-local-motion.png') })
  await page.keyboard.press('Escape')
  await expect(panel).toHaveCount(0)
})
