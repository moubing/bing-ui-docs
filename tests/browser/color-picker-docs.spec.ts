import { expect, test } from '@playwright/test'
import { componentDocsTests, navigateToDocs } from './component-docs'
test.beforeEach(async ({ page }) => { await page.emulateMedia({ reducedMotion: 'reduce' }) })
const open = componentDocsTests({ slug: 'color-picker', title: 'BingColorPicker', ready: '#playground .bing-color-picker', previews: 4, tables: 5,
  sections: ['overview', 'playground', 'presets', 'sizes', 'events-demo', 'props', 'preset-shape', 'events', 'event-list', 'expose', 'types'] })

test('ColorPicker：预设同步、状态与禁用', async ({ page }) => {
  await open(page)
  const trigger = page.getByRole('button', { name: '选择主题颜色', exact: true })
  await trigger.click()
  await page.getByRole('button', { name: '选择 天蓝', exact: true }).click()
  await expect(page.locator('#playground .color-picker-summary')).toContainText('#0ea5e9')
  await page.keyboard.press('Escape')
  await page.getByRole('radiogroup', { name: '颜色选择器状态', exact: true }).getByRole('radio', { name: /^error/ }).locator('..').click()
  await expect(trigger).toHaveAttribute('aria-invalid', 'true')
  await page.getByRole('checkbox', { name: '禁用', exact: true }).locator('..').click()
  await expect(trigger).toBeDisabled()
  await expect(page.getByRole('button', { name: '选择颜色值', exact: true })).toBeEnabled()
})

test('ColorPicker：保留透明度、实例方法和缓存页面清理', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 1000 })
  await open(page)
  await page.locator('#events-demo').getByRole('button', { name: '打开面板', exact: true }).focus()
  await page.keyboard.press('Enter')
  const panel = page.getByRole('dialog', { name: '事件颜色', exact: true })
  await expect(panel).toBeVisible()
  const box = await panel.boundingBox(); expect(box!.x).toBeGreaterThanOrEqual(12); expect(box!.x + box!.width).toBeLessThanOrEqual(378)
  await page.getByRole('textbox', { name: '颜色值', exact: true }).fill('rgba(1, 2, 3, 0.25)')
  await page.getByRole('textbox', { name: '颜色值', exact: true }).press('Enter')
  await expect(page.locator('#events-demo .select-feedback')).toContainText('rgba(1, 2, 3, 0.25)')
  await expect(page.getByRole('button', { name: '事件颜色', exact: true })).toContainText('#01020340')
  await panel.screenshot({ path: info.outputPath('color-picker-light-390.png'), animations: 'disabled' })
  await page.locator('#events-demo').getByRole('button', { name: '关闭面板', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(panel).toHaveCount(0)
  await expect(page.getByRole('button', { name: '事件颜色', exact: true })).toBeFocused()
  await page.getByRole('button', { name: '事件颜色', exact: true }).click()
  const previous = await page.getByRole('button', { name: '事件颜色', exact: true }).elementHandle()
  await navigateToDocs(page, 'button')
  await expect(page.locator('.doc-page h1')).toHaveText('BingButton')
  await expect(panel).toHaveCount(0)
  expect(await previous!.evaluate(node => node.isConnected)).toBe(false)
  await navigateToDocs(page, 'color-picker')
  await expect(page.getByRole('button', { name: '事件颜色', exact: true })).toContainText('#01020340')
})
