import { expect, test } from '@playwright/test'

test('文档公共样式：system 主题实时切换、锚点和 API 横向滚动', async ({ page }, info) => {
  await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' })
  await page.addInitScript(() => {
    if (!localStorage.getItem('bing-ui-docs-theme')) localStorage.setItem('bing-ui-docs-theme', 'system')
  })
  await page.goto('/docs/components/button')
  await expect(page.locator('#playground .doc-example__preview button')).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-bing-theme', 'system')
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(250, 250, 250)')
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: info.outputPath('docs-shell-system-light.png'), animations: 'disabled' })
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(16, 16, 18)')
  await page.screenshot({ path: info.outputPath('docs-shell-system-dark.png'), animations: 'disabled' })
  await page.locator('.docs-toc a').filter({ hasText: /^属性$/ }).click()
  await expect(page).toHaveURL(/#props$/)
  await expect(page.locator('#props h2')).toBeInViewport()
  const table = page.locator('#props .props-table-wrap')
  await table.focus()
  await expect(table).toBeFocused()
  await page.getByRole('button', { name: '切换为浅色主题', exact: true }).click()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-bing-theme', 'light')
})

test('文档公共布局：窄屏目录可收放、Escape 返回、切页和正文首屏', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/docs/components/button')
  await expect(page.locator('#playground .doc-example__preview button')).toBeVisible()
  const toggle = page.getByRole('button', { name: '文档导航', exact: true })
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(page.locator('.doc-page h1')).toBeInViewport()
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: info.outputPath('docs-shell-mobile.png'), animations: 'disabled' })
  await toggle.click()
  await expect(page.locator('.docs-sidebar-scrollbar')).toBeVisible()
  await page.locator('.docs-nav-list a').first().focus()
  await page.keyboard.press('Escape')
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(toggle).toBeFocused()
  await toggle.click()
  await page.locator('.docs-nav-list a[href="/docs/components/input"]').click()
  await expect(page.locator('.doc-page h1')).toHaveText('BingInput')
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await page.goto('/docs/components/input#number')
  await expect(page.locator('#number h2')).toBeInViewport()
  await page.locator('#number .doc-example').screenshot({ path: info.outputPath('input-number-mobile.png'), animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('文档公共布局：200% 字体与长文案保留控件和局部表格滚动', async ({ page }, info) => {
  await page.setViewportSize({ width: 780, height: 1100 })
  await page.goto('/docs/components/button')
  await expect(page.locator('#playground .doc-example__preview button')).toBeVisible()
  await page.addStyleTag({ content: 'html { font-size: 200%; }' })
  await page.locator('#button-label').fill('保存当前配置并继续下一步')
  await expect(page.locator('#playground .doc-example__preview button')).toContainText('保存当前配置并继续下一步')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const table = page.locator('#props .props-table-wrap')
  expect(await page.locator('.site-header a, .site-header button').evaluateAll(nodes => nodes.every(node => {
    const box = node.getBoundingClientRect()
    return box.left >= 0 && box.right <= innerWidth
  }))).toBe(true)
  await table.scrollIntoViewIfNeeded()
  await table.focus()
  await page.keyboard.press('End')
  expect(await table.evaluate(node => node.scrollWidth > node.clientWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath('docs-shell-large-text.png'), animations: 'disabled' })
})
