import { expect, test } from '@playwright/test'
import { componentDocsTests, navigateToDocs } from './component-docs'
test.beforeEach(async ({ page }) => { await page.emulateMedia({ reducedMotion: 'reduce' }) })
const open = componentDocsTests({ slug: 'date-picker', title: 'BingDatePicker', ready: '#types .bing-date-picker', previews: 5, tables: 6,
  sections: ['overview', 'types', 'formats', 'disabled-rules', 'expose', 'props', 'events', 'public-types', 'smooth-options'] })

test('DatePicker：模式与范围切换、确认以及唯一实例 ID', async ({ page }) => {
  await open(page)
  const ids = await page.locator('.bing-date-picker__trigger').evaluateAll(nodes => nodes.map(node => node.id))
  expect(ids).toHaveLength(12); expect(new Set(ids).size).toBe(12)
  await page.getByRole('radiogroup', { name: 'DatePicker 类型', exact: true }).getByRole('radio', { name: /^month/ }).locator('..').click()
  await page.getByRole('checkbox', { name: '范围选择', exact: true }).locator('..').click()
  await page.getByRole('button', { name: '选择日期值', exact: true }).click()
  const panel = page.locator('.bing-date-picker__panel')
  await panel.getByRole('button', { name: '8月', exact: true }).click()
  await expect(panel.getByRole('button', { name: '确定', exact: true })).toBeDisabled()
  await panel.getByRole('button', { name: '10月', exact: true }).click()
  await panel.getByRole('button', { name: '确定', exact: true }).click()
  await expect(page.locator('#types .date-picker-feedback')).toContainText('confirm：2026-08 - 2026-10')
  await page.getByRole('checkbox', { name: '禁用', exact: true }).locator('..').click()
  await expect(page.getByRole('button', { name: '选择日期值', exact: true })).toBeDisabled()
})

test('DatePicker：禁用工作日规则和复制参数同步', async ({ page }) => {
  await open(page)
  await page.getByRole('button', { name: '工作日日期', exact: true }).click()
  const days = page.locator('.bing-date-picker__cell:not(.is-muted)')
  await expect(days.filter({ hasText: /^4$/ })).toBeDisabled()
  await days.filter({ hasText: /^9$/ }).click()
  await expect(page.locator('#disabled-rules .date-picker-feedback')).toContainText('2026-07-09')
  await page.locator('#date-picker-min').fill('2026-07-10')
  await expect(page.locator('#disabled-rules .bing-code-block')).toContainText('"min": "2026-07-10"')
  await page.getByRole('button', { name: '工作日日期', exact: true }).click()
  await expect(days.filter({ hasText: /^9$/ })).toBeDisabled()
})

test('DatePicker：窄屏面板、方法清空和缓存页面卸载', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 1000 })
  await open(page)
  await page.getByRole('button', { name: '选择日期值', exact: true }).click()
  const panel = page.locator('.bing-date-picker__panel')
  await expect(panel.locator('.bing-date-picker__shortcut-rail.is-inline')).toBeVisible()
  const box = await panel.boundingBox(); expect(box!.x).toBeGreaterThanOrEqual(12); expect(box!.x + box!.width).toBeLessThanOrEqual(378)
  await panel.screenshot({ path: info.outputPath('date-picker-light-390.png'), animations: 'disabled' })
  await panel.press('Escape')
  await page.getByRole('button', { name: '打开面板', exact: true }).click()
  await expect(panel).toBeVisible()
  await page.getByRole('button', { name: '清空', exact: true }).focus(); await page.keyboard.press('Enter')
  await expect(panel).toHaveCount(0)
  await expect(page.locator('#expose .date-picker-feedback')).toContainText('当前值：空')
  await page.getByRole('button', { name: '方法日期', exact: true }).click()
  const previous = await page.getByRole('button', { name: '方法日期', exact: true }).elementHandle()
  await navigateToDocs(page, 'button')
  await expect(page.locator('.doc-page h1')).toHaveText('BingButton')
  await expect(panel).toHaveCount(0)
  expect(await previous!.evaluate(node => node.isConnected)).toBe(false)
  await navigateToDocs(page, 'date-picker')
  await expect(page.locator('#expose .date-picker-feedback')).toContainText('当前值：空')
})

test('DatePicker：日历语言切换影响星期和月份，代码同步', async ({ page }) => {
  await open(page)
  const trigger = page.getByRole('button', { name: '选择日期值', exact: true })
  await page.getByRole('radiogroup', { name: '日历语言', exact: true }).getByRole('radio', { name: 'English', exact: true }).locator('..').click()
  await expect(page.locator('#types .bing-code-block__code')).toContainText('"locale": "en-US"')
  await trigger.click()
  const panel = page.locator('.bing-date-picker__panel')
  await expect(panel.getByText('Mon', { exact: true })).toBeVisible()
  await expect(panel.getByRole('button', { name: '选择年份', exact: true })).toContainText('July 2026')
  await expect(panel.getByRole('button', { name: '上个月', exact: true })).toBeVisible()
})
