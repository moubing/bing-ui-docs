import { expect, test } from '@playwright/test'
import { componentDocsTests, navigateToDocs } from './component-docs'
test.beforeEach(async ({ page }) => { await page.emulateMedia({ reducedMotion: 'reduce' }) })
const open = componentDocsTests({ slug: 'select', title: 'BingSelect', ready: '#playground .bing-select', previews: 7, tables: 6,
  sections: ['overview', 'playground', 'multiple', 'detail', 'virtual', 'panel-position', 'sizes-status', 'events-demo', 'props', 'option-shape', 'slots-events', 'slots', 'events', 'types', 'smooth-options'] })
test('Select：搜索配置、实际选择与代码同步', async ({ page }) => {
  await open(page)
  await page.getByRole('radiogroup', { name: '选择器搜索模式', exact: true }).getByRole('radio', { name: /^true/ }).locator('..').click()
  await expect(page.locator('#playground .bing-code-block')).toContainText('"searchable": true')
  await page.getByRole('combobox', { name: '选择城市', exact: true }).click()
  await page.locator('.bing-select__panel').getByRole('combobox').fill('西南')
  await page.getByRole('option', { name: '成都', exact: true }).click()
  await expect(page.locator('#playground .select-feedback')).toContainText('成都')
  await page.getByRole('checkbox', { name: '禁用', exact: true }).locator('..').click()
  await expect(page.getByRole('combobox', { name: '选择城市', exact: true })).toBeDisabled()
})

test('Select：typeahead 与拼音搜索高亮', async ({ page }) => {
  await open(page)
  const trigger = page.getByRole('combobox', { name: '选择城市', exact: true })
  await trigger.press('c')
  await expect(trigger).toContainText('深圳')
  await trigger.press('Enter')
  await trigger.press('c')
  await trigger.press('d')
  await expect(page.locator('.bing-select__option.is-active')).toHaveText('成都')
  await expect(trigger).toContainText('深圳')
  await trigger.press('Enter')
  await expect(trigger).toContainText('成都')
  await page.getByRole('radiogroup', { name: '选择器搜索模式', exact: true }).getByRole('radio', { name: /^true/ }).locator('..').click()
  await trigger.press('Enter')
  await page.locator('.bing-select__search input').fill('hz')
  await expect(page.locator('.bing-picker__match')).toHaveText('杭州')
  await expect(page.locator('.bing-select__option:not([tabindex="-1"])')).toHaveCount(0)
})
test('Select：窄屏面板与缓存页面清理', async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 1000 }); await open(page)
  const trigger = page.getByRole('combobox', { name: '选择城市', exact: true })
  await trigger.click()
  const panel = page.locator('.bing-select__panel')
  const box = await panel.boundingBox(); expect(box!.x).toBeGreaterThanOrEqual(12); expect(box!.x + box!.width).toBeLessThanOrEqual(378)
  await panel.screenshot({ path: info.outputPath('select-light-390.png'), animations: 'disabled' })
  const old = await trigger.elementHandle()
  await trigger.press('Escape')
  await navigateToDocs(page, 'button')
  await expect(page.locator('.doc-page h1')).toHaveText('BingButton'); await expect(panel).toHaveCount(0)
  expect(await old!.evaluate(node => node.isConnected)).toBe(false)
  await navigateToDocs(page, 'select')
  await expect(trigger).toContainText('深圳')
})

test('Select：虚拟列表默认行高与参数代码同步', async ({ page }) => {
  await open(page)
  const trigger = page.getByRole('combobox', { name: '选择大量选项', exact: true })
  // 多选 Tag 的删除按钮覆盖触发器部分区域，使用触发器的键盘入口。
  await trigger.press('Enter')
  await expect(page.locator('.bing-select__panel')).toHaveCSS('--bing-select-default-option-height', '32px')
  await trigger.press('Escape')
  await page.getByRole('textbox', { name: '单项高度', exact: true }).fill('48')
  await expect(page.locator('#virtual .bing-code-block')).toContainText('"virtualItemHeight": 48')
  await trigger.press('Enter')
  await expect(page.locator('.bing-select__panel')).toHaveCSS('--bing-select-default-option-height', '48px')
})
