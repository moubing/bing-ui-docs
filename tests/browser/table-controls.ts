import { expect, type Page } from '@playwright/test'

export async function exerciseTableControls(page: Page) {
  const demo = page.locator('.controls-example')
  const table = demo.locator('.bing-table')
  const firstRow = table.locator('.bing-table__row').first()
  const feedback = demo.locator('p[role="status"]')
  const text = firstRow.locator('.bing-table__cell-value').first()
  await text.scrollIntoViewIfNeeded()
  await text.focus()
  await expect(page.getByRole('tooltip')).toContainText('整理新版组件文档并逐项复核所有示例与默认值')
  await text.press('Escape')
  const input = table.getByRole('textbox', { name: '负责人 a', exact: true })
  await input.fill('新负责人')
  await input.press('ArrowLeft')
  await expect(input).toHaveValue('新负责人')
  await expect(input).toBeFocused()
  await expect(input.locator('xpath=ancestor::*[contains(@class,"bing-table__cell-text")]')).toHaveClass(/has-controls/)
  await expect(page.getByRole('tooltip')).toHaveCount(0)
  await table.getByRole('combobox', { name: '状态 a', exact: true }).click()
  await page.getByRole('option', { name: '复核中', exact: true }).click()
  await firstRow.getByRole('button', { name: '检查', exact: true }).click()
  await expect(feedback).toContainText('已选：无；已检查 a')
  await expect(feedback).not.toContainText('行点击：0')
  await firstRow.locator('.bing-table__cell-text').first().click()
  await expect(feedback).toContainText('已选：a')
}

export async function exerciseTableLoading(page: Page) {
  const demo = page.locator('.controls-example')
  const table = demo.locator('.bing-table')
  const viewport = table.locator('.bing-scrollbar')
  const frame = table.locator('.bing-table__frame')
  await frame.scrollIntoViewIfNeeded()
  const height = (await frame.boundingBox())!.height
  await demo.getByRole('button', { name: '开始加载', exact: true }).click()
  await expect(table).toHaveAttribute('aria-busy', 'true')
  await expect(viewport).toHaveAttribute('inert', '')
  await expect(table.locator('.bing-table__loading-status')).toContainText('正在加载数据')
  await expect(table.getByRole('button', { name: '下一页', exact: true })).toBeDisabled()
  await expect(table.getByRole('combobox', { name: '每页条数', exact: true })).toBeDisabled()
  await demo.getByRole('button', { name: '接收新数据', exact: true }).click()
  await expect(table.locator('.bing-table__row').first()).toContainText('整理新版组件文档')
  expect((await frame.boundingBox())!.height).toBeCloseTo(height, 0)
  await expect(table.getByRole('button', { name: '列设置', exact: true })).toBeEnabled()
  await demo.getByRole('button', { name: '结束加载', exact: true }).click()
  await expect(table).toHaveAttribute('aria-busy', 'false')
  await expect(viewport).not.toHaveAttribute('inert', '')
  await expect(table.locator('.bing-table__row').first()).toContainText('新批次：检查安装说明')
  await expect(table.getByRole('textbox', { name: '负责人 next-a', exact: true })).toBeEditable()
}
